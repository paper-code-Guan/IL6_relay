find_score_file <- function(ct_name, feature_name, tab_dir_src = tab_src){
  ct_id <- safe_file_id(ct_name)
  pat <- c(
    sprintf("^scores_%s_%s_.*\\.csv$", ct_id, feature_name),
    sprintf("^%s_%s_scores_.*\\.csv$", ct_id, feature_name)
  )
  ff <- unique(unlist(lapply(pat, function(p) {
    list.files(tab_dir_src, pattern = p, full.names = TRUE, recursive = TRUE)
  }), use.names = FALSE))
  if (length(ff) != 1L) {
    stop("Expected exactly 1 score file for: ", ct_name, " / ", feature_name,
         "\nPattern: ", paste(pat, collapse = " | "),
         "\nFound:\n", paste(ff, collapse = "\n"))
  }
  ff
}

get_positive <- function(df){
  cn <- colnames(df)

  positive_col <- c("positive", "positive_mask", "aucell_mask")
  positive_col <- positive_col[positive_col %in% cn][1]

  if (!is.na(positive_col)) {
    return(as.logical(df[[positive_col]]))
  }

  stop("Cannot resolve positive-cell column. Columns are:\n",
       paste(cn, collapse = ", "))
}

normalize_mouse_group <- function(x){
  g <- trimws(as.character(x))
  g[g %in% c("WT","wt","Syn-control","syn-control","Control","control")] <- "Syn-control"
  g[g %in% c("KO","ko","Syn-let-7b KO","syn-let-7b ko","Case","case")]   <- "Syn-let-7b KO"
  g
}

score_file_header_cache <- new.env(parent = emptyenv())

read_score_table <- function(ct_name, feature_name, keep_cols = NULL){
  f <- find_score_file(ct_name, feature_name)
  if (is.null(keep_cols)) {
    df <- read.csv(f, stringsAsFactors = FALSE, check.names = FALSE)
  } else {
    header_key <- normalizePath(f, winslash = "/", mustWork = FALSE)
    if (!exists(header_key, envir = score_file_header_cache, inherits = FALSE)) {
      assign(
        header_key,
        names(readr::read_csv(f, n_max = 0, show_col_types = FALSE, progress = FALSE)),
        envir = score_file_header_cache
      )
    }
    file_cols <- get(header_key, envir = score_file_header_cache, inherits = FALSE)
    cols_needed <- unique(c(
      "cell", "Group", "Patient", "orig.ident", "raw_group", "Celltypes_raw",
      "Celltype_use", "Celltype_label", "feature_set",
      "score", "threshold_selected", "threshold_method",
      "positive", "positive_mask", "aucell_mask",
      keep_cols
    ))
    col_select <- intersect(file_cols, cols_needed)
    df <- as.data.frame(readr::read_csv(
      f,
      show_col_types = FALSE,
      progress = FALSE,
      col_select = tidyselect::all_of(col_select)
    ))
  }

  stopifnot("'cell' column missing in score table." = "cell" %in% colnames(df))

  if ("Group" %in% colnames(df)) {
    df$Group <- normalize_mouse_group(df$Group)
  } else if ("raw_group" %in% colnames(df)) {
    df$Group <- ifelse(df$raw_group %in% c("WT","wt"), "Syn-control", "Syn-let-7b KO")
  } else {
    stop("No Group/raw_group column found in score table: ", f)
  }

  df$Group <- factor(df$Group, levels = display_levels)

  if (!"Patient" %in% colnames(df)) {
    if ("orig.ident" %in% colnames(df)) {
      df$Patient <- as.character(df$orig.ident)
    } else {
      stop("No Patient/orig.ident column found in score table: ", f)
    }
  }

  if (!"score" %in% colnames(df)) {
    stop("'score' column missing in score table; cannot proceed.")
  } else {
    df$score <- suppressWarnings(as.numeric(df$score))
  }

  if (!"threshold_selected" %in% colnames(df)) {
    if ("threshold" %in% colnames(df)) {
      df$threshold_selected <- suppressWarnings(as.numeric(df$threshold))
    }
  } else {
    df$threshold_selected <- suppressWarnings(as.numeric(df$threshold_selected))
  }

  df$positive <- get_positive(df)
  df$Celltype_use   <- ct_name
  df$Celltype_label <- pretty_ct(ct_name)
  df$feature_set    <- feature_name

  if (!is.null(keep_cols)) {
    keep_final <- unique(c(
      "cell", "Group", "Patient", "orig.ident", "raw_group", "Celltypes_raw",
      "Celltype_use", "Celltype_label", "feature_set",
      "score", "threshold_selected", "threshold_method", "positive",
      "positive_mask", "aucell_mask", "detection_mask", "rank_mask",
      keep_cols
    ))
    df <- df[, intersect(keep_final, colnames(df)), drop = FALSE]
  }

  df
}

resolve_features_ci <- function(symbols, pool_rows){
  idx <- match(tolower(symbols), tolower(pool_rows))
  res <- ifelse(is.na(idx), NA_character_, pool_rows[idx])
  list(
    found = unique(na.omit(res)),
    missing = unique(symbols[is.na(idx)]),
    mapping = data.frame(
      requested = symbols,
      resolved  = unname(res),
      stringsAsFactors = FALSE
    )
  )
}

compute_single_gene_score_df <- function(seu, ct_name, gene_symbol,
                                         top_percent_default = 0.05,
                                         top_percent_single  = 0.10){
  stopifnot(inherits(seu, "Seurat"))
  stopifnot("Celltype_use missing in Seurat object" = "Celltype_use" %in% colnames(seu@meta.data))
  stopifnot("Group missing in Seurat object" = "Group" %in% colnames(seu@meta.data))

  cells_ct <- rownames(seu@meta.data)[as.character(seu$Celltype_use) == ct_name]
  if (!length(cells_ct)) {
    stop("No cells found for CT: ", ct_name)
  }

  seu_ct <- subset(seu, cells = cells_ct)
  meta_ct <- seu_ct@meta.data

  counts_ct <- seurat_get_layer(seu_ct, assay = "RNA", layer = "counts")

  gene_map <- resolve_features_ci(gene_symbol, rownames(counts_ct))
  genes_found <- gene_map$found
  if (length(genes_found) != 1L) {
    stop("Target single gene not found uniquely: ", gene_symbol,
         "\nFound: ", paste(genes_found, collapse = ", "))
  }

  if (!inherits(counts_ct, "dgCMatrix")) {
    counts_ct <- as(counts_ct, "CsparseMatrix")
  }

  K_top_default <- max(1L, ceiling(top_percent_default * nrow(counts_ct)))
  K_top_single  <- max(1L, ceiling(top_percent_single  * nrow(counts_ct)))

  rankings <- AUCell::AUCell_buildRankings(
    counts_ct,
    plotStats = FALSE,
    verbose = FALSE,
    BPPARAM = BiocParallel::SerialParam()
  )

  # Two AUC calculations: default window (for AUCell threshold transparency)
  # and extended window (for single-gene rank-and-detection positivity).
  gene_set_named <- setNames(list(genes_found), gene_symbol)
  auc_res_default <- AUCell::AUCell_calcAUC(geneSets = gene_set_named, rankings = rankings,
                                            aucMaxRank = K_top_default, verbose = FALSE)
  auc_res_single  <- AUCell::AUCell_calcAUC(geneSets = gene_set_named, rankings = rankings,
                                            aucMaxRank = K_top_single,  verbose = FALSE)

  cells_in_order <- colnames(seu_ct)
  score_vec_default <- as.numeric(AUCell::getAUC(auc_res_default)[gene_symbol, cells_in_order])
  names(score_vec_default) <- cells_in_order
  score_vec_single  <- as.numeric(AUCell::getAUC(auc_res_single )[gene_symbol, cells_in_order])
  names(score_vec_single) <- cells_in_order

  # AUC reported as primary score uses the extended (single-gene) window,
  # consistent with positivity definition.
  score_vec <- score_vec_single

  explore_res <- tryCatch(
    AUCell::AUCell_exploreThresholds(
      auc_res_default,
      plotHist = FALSE,
      smallestPopPercent = 0.25,
      assignCells = TRUE,
      verbose = FALSE
    ),
    error = function(e) {
      message("  AUCell_exploreThresholds failed in compute_single_gene_score_df (",
              ct_name, "/", gene_symbol, "); fallback to Global_k1: ",
              conditionMessage(e))
      NULL
    }
  )

  thr_info <- if (!is.null(explore_res) && !is.null(explore_res[[gene_symbol]])) {
    aucThr <- explore_res[[gene_symbol]]$aucThr
    sel <- as.numeric(aucThr$selected)
    method_name <- "AUCell_default"
    candidates_local <- NULL
    if (!is.null(aucThr$thresholds)) {
      thr_df_df <- as.data.frame(aucThr$thresholds, stringsAsFactors = FALSE)
      thr_col <- if ("threshold" %in% colnames(thr_df_df)) "threshold" else colnames(thr_df_df)[1]
      thr_vals <- suppressWarnings(as.numeric(thr_df_df[[thr_col]]))
      candidates_local <- data.frame(
        method = rownames(thr_df_df),
        threshold = thr_vals,
        stringsAsFactors = FALSE
      )
      if (length(thr_vals) && any(is.finite(thr_vals))) {
        idx <- which.min(abs(thr_vals - sel))
        method_name <- rownames(thr_df_df)[idx]
      }
    }
    if (identical(method_name, "tenPercentOfMax") && !is.null(candidates_local)) {
      gk1_idx <- which(candidates_local$method == "Global_k1")
      if (length(gk1_idx)) {
        gk1_thr <- candidates_local$threshold[gk1_idx[1]]
        if (is.finite(gk1_thr)) {
          sel <- gk1_thr
          method_name <- "Global_k1"
        }
      }
    }
    list(selected = sel, method = method_name)
  } else {
    s <- score_vec_default[is.finite(score_vec_default)]
    sel <- if (length(s) > 1 && stats::sd(s) > 0) mean(s) + 2 * stats::sd(s) else max(s, 0) + .Machine$double.eps
    list(selected = sel, method = "Global_k1_fallback")
  }

  aucell_mask <- score_vec_default > thr_info$selected
  aucell_mask[!is.finite(score_vec_default)] <- FALSE

  # Single-gene rank-and-detection positivity using the extended window:
  #   positive = (AUC > 0 at extended window, i.e., rank ≤ K_top_single) OR
  #              (raw count > 0)
  expr_count_proxy <- as.numeric(counts_ct[genes_found, cells_in_order, drop = TRUE])
  names(expr_count_proxy) <- cells_in_order
  detection_mask <- expr_count_proxy > 0
  detection_mask[!is.finite(expr_count_proxy)] <- FALSE

  rank_mask <- score_vec_single > 0
  rank_mask[!is.finite(score_vec_single)] <- FALSE

  positive_mask <- rank_mask | detection_mask

  patient_vec <- if ("orig.ident" %in% colnames(meta_ct)) {
    as.character(meta_ct[cells_in_order, "orig.ident", drop = TRUE])
  } else {
    stop("'orig.ident' is missing in meta_ct; animal identities cannot be resolved.")
  }

  df <- data.frame(
    cell                  = cells_in_order,
    Group                 = factor(as.character(meta_ct[cells_in_order, "Group"]), levels = display_levels),
    Patient               = patient_vec,
    raw_group             = as.character(meta_ct[cells_in_order, "raw_group"]),
    Celltypes_raw         = as.character(meta_ct[cells_in_order, "Celltypes_raw"]),
    Celltype_use          = ct_name,
    Celltype_label        = pretty_ct(ct_name),
    feature_set           = gene_symbol,
    features_requested    = gene_symbol,
    features_found        = genes_found,
    n_features_found      = 1L,
    score                 = score_vec,
    score_default_window  = score_vec_default,
    expr_count_proxy      = expr_count_proxy,
    threshold_selected    = thr_info$selected,
    threshold_method      = thr_info$method,
    K_top_used            = K_top_single,
    aucell_mask           = as.logical(aucell_mask),
    detection_mask        = as.logical(detection_mask),
    rank_mask             = as.logical(rank_mask),
    positive              = as.logical(positive_mask),
    detection_used        = TRUE,
    stringsAsFactors      = FALSE
  )

  df
}

plot_score_single_panel <- function(data,
                                   y_var = "score",
                                   title = NULL,
                                   y_label = "AUC score",
                                   group_levels = NULL,
                                   group_colors = NULL,
                                   axis_title_size = 23,
                                   axis_text_size  = 23,
                                   font_family_main = plot_font_family,
                                   point_size = 2.0,
                                   point_alpha = 1.00,
                                   point_stroke = 0,
                                   jitter_w = 0.12,
                                   violin_alpha = 0.80,
                                   violin_line_pt = 0.6,
                                   axis_line_pt = 0.8,
                                   stat_label_size_pt = 20,
                                   p_label_size_pt    = 21,
                                   show_stats = TRUE){

  if (!"Group" %in% colnames(data)) {
    stop("Group column missing.")
  }
  if (!y_var %in% colnames(data)) {
    stop(paste0(y_var, " column missing."))
  }

  if (is.null(group_levels)) {
    group_levels <- c("Syn-control", "Syn-let-7b KO")
  }

  if (is.null(group_colors)) {
    group_colors <- c(
      "Syn-control"   = "#7FB2D5",
      "Syn-let-7b KO" = "#F47F72"
    )
  }

  group_colors <- group_colors[group_levels]

  data <- data %>%
    mutate(Group = factor(normalize_mouse_group(Group), levels = group_levels)) %>%
    filter(Group %in% group_levels)

  if (nrow(data) == 0) {
    stop("No rows left after Group filtering.")
  }

  # ---------------------------------------------------------------------------
  # Mouse inference uses a cell-level GLMM with a random animal intercept.
  # Jittered points and group means are animal-level summaries.
  # ---------------------------------------------------------------------------
  if (!"Patient" %in% colnames(data)) {
    stop("'Patient' column missing in score table. Re-run step 4 so animal identities are written to the score tables.")
  }
  mixed_test <- mixed_score_group_test(data, y_var, group_levels)

  data <- data %>%
    group_by(Patient, Group) %>%
    summarise(.plot_value = mean(.data[[y_var]], na.rm = TRUE), .groups = "drop") %>%
    ungroup()
  names(data)[names(data) == ".plot_value"] <- y_var

  stats_df <- data %>%
    group_by(Group) %>%
    summarise(
      mean_value = mean(.data[[y_var]], na.rm = TRUE),
      .groups = "drop"
    )

  p_val <- mixed_test$primary_p[1]
  p_lab <- format_p_method(p_val, "GLMM")

  rng <- range(data[[y_var]], na.rm = TRUE)
  if (!all(is.finite(rng))) rng <- c(0, 1)

  d <- diff(rng)
  if (d == 0) d <- max(abs(rng[1]), 0.001)

  ## show_stats=TRUE: add headroom for Mean and P labels.
  ## show_stats=FALSE: keep y-axis close to the data range to avoid passive y-max inflation.
  if (show_stats) {
    y_low  <- rng[1] - 0.06 * d
    y_high <- rng[2] + 0.62 * d
    y_mean <- y_high - 0.06 * d
    y_p    <- y_high - 0.18 * d
  } else {
    y_low  <- rng[1] - 0.04 * d
    y_high <- rng[2] + 0.04 * d
  }

  p <- ggplot(data, aes(x = Group, y = .data[[y_var]], fill = Group, colour = Group)) +
    geom_point(
      position = position_jitter(width = jitter_w, height = 0),
      alpha = point_alpha,
      size = point_size,
      stroke = point_stroke,
      shape = 16
    ) +
    stat_summary(
      fun = mean,
      geom = "crossbar",
      width = 0.55,
      colour = "black",
      linewidth = 0.45
    ) +
    scale_fill_manual(values = group_colors) +
    scale_colour_manual(values = group_colors) +
    scale_y_continuous(limits = c(y_low, y_high)) +
    labs(title = title, x = NULL, y = y_label) +
    theme_classic(base_size = axis_text_size, base_family = font_family_main) +
    theme(
      plot.title   = element_text(size = axis_title_size, face = "bold", hjust = 0.5),
      axis.title.y = element_text(size = axis_title_size, face = "bold"),
      axis.text.x  = element_text(size = min(axis_text_size, group_axis_text_size), face = "bold"),
      axis.text.y  = element_text(size = axis_text_size, face = "bold"),
      axis.line    = element_line(linewidth = axis_line_pt),
      legend.position = "none",
      plot.margin = margin(10, 10, 12, 10)
    ) +
    theme_axis_black()

  if (show_stats) {
    eff_estimate <- mixed_test$effect_estimate[1]
    eff_ci_low <- mixed_test$effect_ci_low[1]
    eff_ci_high <- mixed_test$effect_ci_high[1]
    if (!is.na(eff_estimate) && !is.na(eff_ci_low) && !is.na(eff_ci_high)) {
      eff_lab <- sprintf("dScore = %.4f (95%% CI %.4f-%.4f)", eff_estimate, eff_ci_low, eff_ci_high)
    } else {
      eff_lab <- "dScore = NA"
    }
    ctrl_mean <- stats_df$mean_value[stats_df$Group == group_levels[1]]
    case_mean <- stats_df$mean_value[stats_df$Group == group_levels[2]]
    arrow_lab <- if (length(case_mean) && length(ctrl_mean) &&
                     is.finite(case_mean) && is.finite(ctrl_mean)) {
      if (case_mean > ctrl_mean) {
        "KO up"
      } else if (case_mean < ctrl_mean) {
        "KO down"
      } else {
        "no change"
      }
    } else {
      "NA"
    }
    p <- p +
      geom_text(
        data = stats_df,
        aes(
          x = Group,
          y = y_mean,
          label = sprintf("Mean = %.4f", mean_value)
        ),
        inherit.aes = FALSE,
        family = font_family_main,
        fontface = "bold",
        vjust = 0,
        size = stat_label_size_pt / 10,
        colour = "black"
      ) +
      annotate(
        "text",
        x = (length(group_levels) + 1) / 2,
        y = y_p + 0.18 * d,
        label = paste0(eff_lab, "    ", arrow_lab),
        family = font_family_main,
        fontface = "bold",
        vjust = 0,
        size = (p_label_size_pt - 2) / 10,
        colour = "black"
      ) +
      annotate(
        "text",
        x = (length(group_levels) + 1) / 2,
        y = y_p,
        label = p_lab,
        family = font_family_main,
        fontface = "italic",
        vjust = 0,
        size = p_label_size_pt / 10,
        colour = "black"
      )
  }

  list(
    plot = p,
    p_value = p_val,
    stats = stats_df,
    test_stats = mixed_test
  )
}



add_umap_arrow_axes <- function(plot_obj, axis_df, x_col = "UMAP_1", y_col = "UMAP_2") {
