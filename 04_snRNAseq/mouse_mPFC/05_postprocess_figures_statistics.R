compute_proportion_test_pair <- function(df, ct_name, feature_name) {
  stopifnot("positive" %in% colnames(df),
            "Patient" %in% colnames(df),
            "Group" %in% colnames(df))

  df <- df %>%
    mutate(
      Group = factor(normalize_mouse_group(Group), levels = display_levels),
      Patient = as.factor(Patient),
      .positive = as.integer(as.logical(positive))
    ) %>%
    filter(Group %in% display_levels, !is.na(Patient), !is.na(.positive))

  per_animal <- df %>%
    group_by(Patient, Group) %>%
    summarise(
      n_total = dplyr::n(),
      n_positive = sum(.positive, na.rm = TRUE),
      proportion = ifelse(n_total > 0, n_positive / n_total, NA_real_),
      .groups = "drop"
    ) %>%
    mutate(Celltype_use = ct_name, feature_set = feature_name)

  if (nrow(df) < 2 || length(unique(df$Group)) < 2 || length(unique(df$Patient)) < 2 ||
      length(unique(df$.positive)) < 2) {
    glmm_p <- NA_real_
    glmm_warning_flag <- TRUE
    glmm_warning_msg <- "insufficient groups, animals or binary outcome variation"
    glmm_error_msg <- ""
    eff_glmm <- list(
      estimate = NA_real_,
      se = NA_real_,
      ci_low = NA_real_,
      ci_high = NA_real_,
      p_value = NA_real_
    )
  } else {
    glmm_fit <- fit_glmmTMB_with_warnings(
      glmmTMB::glmmTMB(.positive ~ Group + (1 | Patient), data = df, family = binomial())
    )
    eff_glmm <- extract_glmmTMB_effect(glmm_fit$fit, "^Group")
    glmm_p <- eff_glmm$p_value
    glmm_warning_flag <- glmm_fit$warning_flag
    glmm_warning_msg <- glmm_fit$warning
    glmm_error_msg <- glmm_fit$error
  }

  n_zero_ctrl <- sum(per_animal$Group == display_levels[1] & per_animal$proportion == 0, na.rm = TRUE)
  n_zero_case <- sum(per_animal$Group == display_levels[2] & per_animal$proportion == 0, na.rm = TRUE)
  n_ctrl <- sum(per_animal$Group == display_levels[1], na.rm = TRUE)
  n_case <- sum(per_animal$Group == display_levels[2], na.rm = TRUE)
  fc_ha <- compute_fold_change_HA(
    per_animal,
    ctrl_level = display_levels[1],
    case_level = display_levels[2],
    pseudocount = 0.5
  )

  list(
    per_animal = per_animal,
    glmm_p = glmm_p,
    glmm_warning_flag = glmm_warning_flag,
    glmm_warning_msg = glmm_warning_msg,
    glmm_error_msg = glmm_error_msg,
    n_total_cells = nrow(df),
    n_animals_per_group = sprintf("%d/%d", n_ctrl, n_case),
    n_animals_zero_positive_ctrl = n_zero_ctrl,
    n_animals_zero_positive_case = n_zero_case,
    log_OR = eff_glmm$estimate,
    log_OR_se = eff_glmm$se,
    log_OR_ci_low = eff_glmm$ci_low,
    log_OR_ci_high = eff_glmm$ci_high,
    OR = exp(eff_glmm$estimate),
    OR_ci_low = exp(eff_glmm$ci_low),
    OR_ci_high = exp(eff_glmm$ci_high),
    ctrl_rate_HA = fc_ha$ctrl_rate_HA,
    case_rate_HA = fc_ha$case_rate_HA,
    fold_change_HA = fc_ha$fold_change,
    log2_fc_HA = fc_ha$log2_fc,
    pseudocount_method = fc_ha$pseudocount_method
  )
}

