    group_by(Celltype_use) %>%
    summarise(
      UMAP_1 = median(UMAP_1, na.rm = TRUE),
      UMAP_2 = median(UMAP_2, na.rm = TRUE),
      .groups = "drop"
    ) %>%
    mutate(label = pretty_ct_fig(Celltype_use))

  positive_df <- plot_df %>% filter(positive %in% TRUE)

  p <- ggplot() +
    geom_point(
      data = plot_df,
      aes(UMAP_1, UMAP_2),
      color = "#D9D9D9",
      size = 0.45,
      alpha = 0.85,
      shape = 16,
      show.legend = FALSE
    ) +
    geom_point(
      data = positive_df,
      aes(UMAP_1, UMAP_2),
      color = "#D7301F",
      size = 0.45,
      alpha = 0.95,
      shape = 16,
      show.legend = FALSE
    ) +
    geom_text_repel(
      data = label_df,
      aes(UMAP_1, UMAP_2, label = label),
      color = "black",
      size = 4.5,
      segment.color = "black",
      box.padding = 0.40,
      point.padding = 0.15,
      show.legend = FALSE
    ) +
    labs(x = "UMAP1", y = "UMAP2") +
    theme_classic(base_size = 12) +
    theme(
      panel.grid      = element_blank(),
      panel.border    = element_blank(),
      axis.text       = element_blank(),
      axis.ticks      = element_blank(),
      axis.title      = element_text(size = 16),
      legend.position = "none"
    )

  p <- add_umap_arrow_axes(p, plot_df)

  save_plot_pdf(
    p,
    file.path(fig_dir, sprintf("%s_%s.pdf", out_name, timestamp_tag)),
    width = 178, height = 161, units = "mm"
  )

  if (isTRUE(write_positive_cells)) {
    write.csv(
      positive_df,
      file.path(source_tab_dir, sprintf("%s_positive_cells_%s.csv", out_name, timestamp_tag)),
      row.names = FALSE
    )
  }

  invisible(p)
}

