mixed_score_group_test <- function(data, y_var, group_levels = display_levels){
  df <- data %>%
    mutate(
      Group = factor(normalize_mouse_group(Group), levels = group_levels),
      Patient = as.factor(Patient),
      .y = as.numeric(.data[[y_var]])
    ) %>%
    filter(Group %in% group_levels, is.finite(.y), !is.na(Patient))

  if (nrow(df) < 2 || length(unique(df$Group)) < 2 || length(unique(df$Patient)) < 2) {
    return(data.frame(
      primary_method = "glmmTMB_gaussian_random_patient",
      primary_p = NA_real_,
