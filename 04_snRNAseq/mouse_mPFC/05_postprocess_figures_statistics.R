# ---------------------------------------------------------
make_one_ct_positive_count <- function(df, ct_name){
  if (!"Patient" %in% colnames(df)) {
    stop("'Patient' column missing in score table for ", ct_name,
         "; rerun step 4 so animal identities are written.")
  }
  df %>%
    mutate(Group = factor(normalize_mouse_group(Group), levels = display_levels)) %>%
    filter(Group %in% display_levels) %>%
    group_by(Patient, Group) %>%
    summarise(
      donor_total_cells = dplyr::n(),
      donor_il6_pos = sum(positive, na.rm = TRUE),
      donor_il6_prop = ifelse(donor_total_cells > 0, donor_il6_pos / donor_total_cells, NA_real_),
      .groups = "drop"
    ) %>%
    group_by(Group) %>%
    summarise(
      n_animals = dplyr::n(),
      total_cells = sum(donor_total_cells, na.rm = TRUE),
      il6_pos = sum(donor_il6_pos, na.rm = TRUE),
      il6_prop = mean(donor_il6_prop, na.rm = TRUE),
      il6_prop_se = stats::sd(donor_il6_prop, na.rm = TRUE) / sqrt(n_animals),
      .groups = "drop"
    ) %>%
    right_join(data.frame(Group = factor(display_levels, levels = display_levels)), by = "Group") %>%
    mutate(
      n_animals = ifelse(is.na(n_animals), 0L, n_animals),
      total_cells = ifelse(is.na(total_cells), 0L, total_cells),
      il6_pos     = ifelse(is.na(il6_pos), 0L, il6_pos),
      il6_prop = ifelse(is.na(il6_prop), NA_real_, il6_prop),
      il6_prop_se = ifelse(is.na(il6_prop_se), NA_real_, il6_prop_se)
    ) %>%
    mutate(
      ct_in_obj = ct_name,
      ct_short  = c("ExcitNeu"="ExtNeu","InhibNeu"="InbNeu","Ast"="Astro","Mic"="MiGlia","OL"="Oligo")[ct_name]
    ) %>%
    relocate(ct_in_obj, ct_short, Group)
}

