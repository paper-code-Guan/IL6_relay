write_forest_caption <- function(forest_data, out_txt){
  sg <- forest_data$single_gene
  mod <- forest_data$module

  # Caption text adapts to whichever of Mic / OL is included this run.
  cts_in_plot <- c("ExtNeu", "InbNeu", "Astro")
  if (mic_avail$has_mic)    cts_in_plot <- c(cts_in_plot, "MiGlia")
  if (oligo_avail$has_oligo) cts_in_plot <- c(cts_in_plot, "Oligo")
  ct_list_str <- paste(cts_in_plot, collapse = ", ")
  n_cts <- length(cts_in_plot)
  count_word <- c("three", "four", "five", "six")[max(1L, min(4L, n_cts - 2L))]

  excluded_msgs <- character(0)
  if (!mic_avail$has_mic) {
    excluded_msgs <- c(excluded_msgs,
      "microglia were not analysed because the per-group cell/animal count did not meet the prespecified microglia-availability thresholds (see Locked_parameters)")
  }
  if (!oligo_avail$has_oligo) {
    excluded_msgs <- c(excluded_msgs,
      "oligodendrocytes were not analysed because the per-group cell/animal count did not meet the prespecified oligodendrocyte-availability thresholds (see Locked_parameters)")
  }
  exclusion_str <- if (length(excluded_msgs)) paste0("; ", paste(excluded_msgs, collapse = "; ")) else ""

  mode_str <- sprintf("across the %s main cell classes (%s)%s",
                      count_word, ct_list_str, exclusion_str)
  sg_dir <- sg %>%
    transmute(prior_direction, direction_match) %>%
    filter(!is.na(prior_direction), prior_direction != 0)
  mod_dir <- mod %>%
    transmute(prior_direction, direction_match) %>%
    filter(!is.na(prior_direction), prior_direction != 0)
  direction_consistency_sg <- if (nrow(sg_dir)) {
    sprintf("%d/%d", sum(sg_dir$direction_match, na.rm = TRUE), nrow(sg_dir))
  } else {
    "NA"
  }
  direction_consistency_mod <- if (nrow(mod_dir)) {
    sprintf("%d/%d", sum(mod_dir$direction_match, na.rm = TRUE), nrow(mod_dir))
  } else {
    "NA"
  }

  cap_lines <- c(
    "Forest plot caption (auto-generated):",
    "",
    paste("Forest plot of Syn-let-7b KO vs Syn-control effect", paste0(mode_str, ",")),
    "with two panels:",
    "  Left: single-gene IL-6 log Odds Ratio from binomial GLMM (animal random",
    "        intercept), two-sided 95% CI shown as horizontal bars; per-row",
    "        annotation reports log OR and the two-sided P value.",
    "  Right: IL-6/JAK/STAT3 module score Cohen's d standardised by within-",
    "        cell-type pooled cell-level SD, derived from gaussian GLMM with",
    "        animal random intercept; per-row annotation reports d and P.",
    "",
    "P values are two-sided; q values are Benjamini-Hochberg adjusted within",
    "feature family (single-gene proportion family vs module score family)",
    "and are reported in the source data CSV only (not rendered on the figure).",
    "Diamond markers indicate point estimates; horizontal bars indicate 95% CI.",
    "Vertical dashed line at zero indicates null effect.",
    "",
    "Statistical testing follows Squair et al. 2021 (PMID 34584091) analysis-unit-level",
    "inference, with cell-level data nested within animals.",
    "",
    "Source data: see mouse_IL6_forest_plot_source_data_*.csv"
  )
  writeLines(cap_lines, con = out_txt)
}

