# For the figure annotation we report the animal-level Wilcoxon test on
# per-animal (ExcitNeu - InhibNeu) IL6+ proportion delta as the primary
# inference for whether the two neuron classes show distinct response
# magnitudes. Animal-level Wilcoxon avoids GLMM Wald-test inflation under
# rare-event complete separation in small cohorts (Squair et al. 2021).
# The cell-level GLMM interaction is retained as a sensitivity column.
p_used <- if (is.finite(Pval_wilcox)) Pval_wilcox else Pval_glmm
if (is.finite(p_used)) {
  p_txt <- if (p_used < 1e-3) {
    "<0.001"
  } else if (p_used >= 0.999) {
    ">0.99"
  } else {
    sprintf("%.3f", p_used)
  }
}

