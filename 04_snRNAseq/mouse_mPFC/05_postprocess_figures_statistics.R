    sd_pool <- sd(df$score, na.rm = TRUE)
    n_ctrl_d <- length(unique(df$Patient[df$Group == display_levels[1]]))
    n_case_d <- length(unique(df$Patient[df$Group == display_levels[2]]))
    cohens_d <- if (is.finite(sd_pool) && sd_pool > 0) test$effect_estimate[1] / sd_pool else NA_real_
    cohens_d_ci_low <- if (is.finite(sd_pool) && sd_pool > 0) test$effect_ci_low[1] / sd_pool else NA_real_
    cohens_d_ci_high <- if (is.finite(sd_pool) && sd_pool > 0) test$effect_ci_high[1] / sd_pool else NA_real_
    q_val <- main_p_df %>%
      filter(Celltype_use == ct, feature_set == msigdb_il6_jak_stat3_feature) %>%
      pull(q_BH)
    data.frame(
      cell_type = ct,
      feature_layer = "module_IL6_JAK_STAT3",
      effect_metric = "mean_diff_score",
      estimate = test$effect_estimate[1],
      ci_low = test$effect_ci_low[1],
      ci_high = test$effect_ci_high[1],
      OR = NA_real_,
      OR_ci_low = NA_real_,
      OR_ci_high = NA_real_,
      p_value = test$primary_p[1],
      q_BH = if (length(q_val)) q_val[1] else NA_real_,
      n_total_cells = test$n_cells[1],
      n_animals_per_group = sprintf("%d/%d", n_ctrl_d, n_case_d),
      prior_direction = get_prior_direction(ct, msigdb_il6_jak_stat3_feature),
      observed_direction = sign(test$effect_estimate[1]),
      direction_match = !is.na(get_prior_direction(ct, msigdb_il6_jak_stat3_feature)) &&
        !is.na(sign(test$effect_estimate[1])) &&
        (get_prior_direction(ct, msigdb_il6_jak_stat3_feature) == 0 ||
           sign(get_prior_direction(ct, msigdb_il6_jak_stat3_feature)) == sign(test$effect_estimate[1])),
      fold_change_HA = NA_real_,
      cohens_d = cohens_d,
      cohens_d_ci_low = cohens_d_ci_low,
      cohens_d_ci_high = cohens_d_ci_high,
      mean_diff = test$effect_estimate[1],
      mean_diff_ci_low = test$effect_ci_low[1],
      mean_diff_ci_high = test$effect_ci_high[1],
      stringsAsFactors = FALSE
    )
  }))

  list(single_gene = sg_data, module = mod_data)
}

format_pq_label <- function(x, prefix) {
  vapply(x, function(v) {
    if (is.na(v) || !is.finite(v)) return(paste0(prefix, "=NA"))
    if (v < 0.001) return(paste0(prefix, "<0.001"))
    sprintf("%s=%.3f", prefix, v)
  }, character(1))
}

