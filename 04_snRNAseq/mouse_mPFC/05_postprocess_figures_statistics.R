# ---------------------------------------------------------
# 19c) Per-figure source-data + statistics manifest (TXT)
#
#      Lists every PDF under figures/ alongside the CSV that holds the
#      Prism-rebuildable raw data, the statistical method, and the CSV
#      that holds the test statistic + P value. Maintained automatically
#      from filename patterns.
# ---------------------------------------------------------
build_figure_data_stat_manifest_mouse <- function() {
  rel_path <- function(p) {
    if (length(p) == 0 || is.na(p) || !nzchar(p)) return(NA_character_)
    tryCatch(sub(paste0("^", normalizePath(out_root, winslash = "/", mustWork = FALSE), "/?"), "",
                 normalizePath(p, winslash = "/", mustWork = FALSE)),
             error = function(e) p)
  }
  pick_one <- function(dir, pat) {
    ff <- list.files(dir, pattern = pat, full.names = TRUE, recursive = TRUE)
    if (!length(ff)) return(NA_character_)
    ff[order(file.info(ff)$mtime, decreasing = TRUE)][1]
  }
  pdfs <- list.files(fig_dir, pattern = "\\.pdf$", full.names = TRUE)
  pdfs <- pdfs[order(basename(pdfs))]

  classify_one_pdf <- function(pdf_full) {
    pdf_name <- basename(pdf_full)
    src <- NA_character_; stats_file <- NA_character_
    method <- "Descriptive only (no inferential test for this figure)"
    aux  <- character(0)

    m <- regmatches(pdf_name, regexec("^mouse_([A-Za-z0-9]+)_IL6_score_(with|no)_stats_", pdf_name))[[1]]
    if (length(m) == 3) {
      ct <- m[2]
      src <- pick_one(source_tab_dir, sprintf("^mouse_%s_IL6_score_source_data_.*\\.csv$", ct))
      stats_file <- pick_one(stat_tab_dir, "^mouse_score_GLMM_primary_.*\\.csv$")
      method <- "AUC score two-group: GLMM (gaussian, 1|Patient) primary"
      return(list(src=src, method=method, stats=stats_file, aux=aux))
    }
    m <- regmatches(pdf_name, regexec("^mouse_([A-Za-z0-9]+)_IL6_positive_proportion_(with|no)_stats_", pdf_name))[[1]]
    if (length(m) == 3) {
      ct <- m[2]
      src <- pick_one(source_tab_dir, sprintf("^mouse_%s_IL6_positive_proportion_source_data_.*\\.csv$", ct))
      stats_file <- pick_one(stat_tab_dir, "^proportion_pvalues_BH_adjusted_.*\\.csv$")
      method <- "IL6+ proportion two-group: GLMM-binomial (1|Patient) primary; BH-FDR across CT family"
      aux <- pick_one(stat_tab_dir, "^mouse_il6_positive_GLMM_primary_.*\\.csv$")
      return(list(src=src, method=method, stats=stats_file, aux=aux))
    }
    m <- regmatches(pdf_name, regexec("^mouse_([A-Za-z0-9]+)_MSigDB_Hallmark_IL6_JAK_STAT3_signaling_score_(with|no)_stats_", pdf_name))[[1]]
    if (length(m) == 3) {
      ct <- m[2]
      src <- pick_one(source_tab_dir, sprintf("^mouse_%s_MSigDB_Hallmark_IL6_JAK_STAT3_signaling_score_source_data_.*\\.csv$", ct))
      stats_file <- pick_one(stat_tab_dir, "^main_pvalues_BH_adjusted_.*\\.csv$")
      method <- "MSigDB IL6/JAK/STAT3 module score two-group: GLMM (gaussian, 1|Patient) primary; BH-FDR across CT family"
      aux <- pick_one(stat_tab_dir, "^mouse_score_GLMM_primary_.*\\.csv$")
      return(list(src=src, method=method, stats=stats_file, aux=aux))
    }
    if (grepl("^mouse_Ast_GFAP_score_", pdf_name)) {
      src <- pick_one(source_tab_dir, "^mouse_Ast_GFAP_score_source_data_.*\\.csv$")
      stats_file <- pick_one(stat_tab_dir, "^mouse_score_GLMM_primary_.*\\.csv$")
      method <- "GFAP AUC score two-group: GLMM gaussian primary"
      return(list(src=src, method=method, stats=stats_file, aux=aux))
    }
    if (grepl("^mouse_Ast_GFAP_positive_proportion_", pdf_name)) {
      src <- pick_one(source_tab_dir, "^mouse_Ast_GFAP_positive_proportion_source_data_.*\\.csv$")
      stats_file <- pick_one(stat_tab_dir, "^proportion_pvalues_BH_adjusted_.*\\.csv$")
      method <- "GFAP+ proportion two-group: GLMM-binomial primary"
      return(list(src=src, method=method, stats=stats_file, aux=aux))
    }
    if (grepl("^mouse_Mic_AIF1_score_", pdf_name)) {
      src <- pick_one(source_tab_dir, "^mouse_Mic_AIF1_score_source_data_.*\\.csv$")
      stats_file <- pick_one(stat_tab_dir, "^mouse_score_GLMM_primary_.*\\.csv$")
      method <- "AIF1 AUC score two-group: GLMM gaussian primary"
      return(list(src=src, method=method, stats=stats_file, aux=aux))
    }
    if (grepl("^mouse_Mic_AIF1_positive_proportion_", pdf_name)) {
      src <- pick_one(source_tab_dir, "^mouse_Mic_AIF1_positive_proportion_source_data_.*\\.csv$")
      stats_file <- pick_one(stat_tab_dir, "^proportion_pvalues_BH_adjusted_.*\\.csv$")
      method <- "AIF1+ proportion two-group: GLMM-binomial primary"
      return(list(src=src, method=method, stats=stats_file, aux=aux))
    }
    if (grepl("^mouse_il6_positive_proportion_heatmap_grouped_", pdf_name)) {
      src <- pick_one(source_tab_dir, "^mouse_il6_positive_proportion_heatmap_source_data_.*\\.csv$")
      stats_file <- pick_one(stat_tab_dir, "^mouse_il6_positive_GLMM_primary_.*\\.csv$")
      method <- "Per-CT animal-level IL6+ mean rate shown as Syn-control / Syn-let-7b KO numeric tiles, plus log2FC = log2(KO/CTR) heatmap tile; per-CT inferential P retained in linked stats CSV"
      return(list(src=src, method=method, stats=stats_file, aux=aux))
    }
    if (grepl("^mouse_il6_positive_proportion_interaction_", pdf_name) ||
        grepl("^mouse_il6_proportion_interaction_", pdf_name)) {
      src <- pick_one(source_tab_dir, "^mouse_il6_positive_interaction_input_.*\\.csv$")
      if (is.na(src)) src <- pick_one(source_tab_dir, "^mouse_il6_proportion_interaction_input_.*\\.csv$")
      stats_file <- pick_one(stat_tab_dir, "^mouse_il6_positive_interaction_.*Wilcoxon.*\\.csv$")
      if (is.na(stats_file)) stats_file <- pick_one(stat_tab_dir, "^mouse_il6_proportion_interaction_.*\\.csv$")
      method <- "Animal-level Wilcoxon on delta(p_ExN - p_InN) per group (primary); cell-level binomial GLMM group-by-cell-type interaction (sensitivity)"
      return(list(src=src, method=method, stats=stats_file, aux=aux))
    }
    if (grepl("^mouse_IL6_forest_plot_", pdf_name)) {
      src <- pick_one(source_tab_dir, "^mouse_IL6_forest_plot_source_data_.*\\.csv$")
      aux <- pick_one(fig_dir,        "^mouse_IL6_forest_plot_caption_.*\\.txt$")
      stats_file <- pick_one(stat_tab_dir, "^proportion_pvalues_BH_adjusted_.*\\.csv$")
      method <- "Single-gene IL6: log OR with 95% CI (GLMM-binomial); Module: Cohen's d with 95% CI (GLMM-gaussian); two-sided P; BH-FDR within feature family"
      return(list(src=src, method=method, stats=stats_file, aux=aux))
    }
    if (grepl("^mouse_il6_positive_composition_main[0-9]+_donut_", pdf_name)) {
      n_match <- regmatches(pdf_name, regexec("main([0-9]+)_donut", pdf_name))[[1]]
      n <- if (length(n_match) >= 2) n_match[2] else "N"
      src <- pick_one(composition_tab_dir, sprintf("^mouse_il6_positive_composition_main%s_.*\\.csv$", n))
      method <- "Descriptive composition: each cell type's IL6+ cell count as % of summed IL6+ cells across the main cell-type set"
      return(list(src=src, method=method, stats=stats_file, aux=aux))
    }
    if (grepl("^mouse_celltype_composition_donut_", pdf_name)) {
      src <- pick_one(composition_tab_dir, "^mouse_celltype_composition_.*\\.csv$")
      method <- "Descriptive cell-type composition (% of all cells)."
      return(list(src=src, method=method, stats=stats_file, aux=aux))
    }
    if (grepl("^mouse_celltype_counts_barplot_", pdf_name)) {
      src <- pick_one(composition_tab_dir, "^mouse_celltype_counts_.*\\.csv$")
      method <- "Descriptive cell counts per cell type."
      return(list(src=src, method=method, stats=stats_file, aux=aux))
    }
    if (grepl("^mouse_celltype_umap_", pdf_name)) {
      src <- pick_one(source_tab_dir, "^mouse_celltype_umap_source_data_.*\\.csv$")
      method <- "Descriptive UMAP embedding coloured by cell type (no test)."
      return(list(src=src, method=method, stats=stats_file, aux=aux))
    }
    if (grepl("^mouse_il6_positive_umap_", pdf_name)) {
      src <- pick_one(source_tab_dir, "^mouse_il6_positive_umap_source_data_.*\\.csv$")
      m_pos <- regmatches(pdf_name, regexec("^(mouse_il6_positive_umap_(?:main[0-9]+|all_celltypes(?:_(?:ctr|ko))?))_", pdf_name, perl = TRUE))[[1]]
      stem <- if (length(m_pos) >= 2) m_pos[2] else "mouse_il6_positive_umap"
      aux <- pick_one(source_tab_dir, sprintf("^%s_positive_cells_.*\\.csv$", stem))
      method <- "Descriptive UMAP highlighting AUCell IL6+ cells (red) vs the rest (grey). Same dot diameter for both. No test."
      return(list(src=src, method=method, stats=stats_file, aux=aux))
    }
    if (grepl("^mouse_il6_count_positive_umap_", pdf_name)) {
      src <- pick_one(source_tab_dir, "^mouse_il6_count_positive_umap_source_data_.*\\.csv$")
      method <- "Descriptive UMAP highlighting cells with raw Il6 count > 0. No test."
      return(list(src=src, method=method, stats=stats_file, aux=aux))
    }
    if (grepl("^mouse_marker_dotplot_", pdf_name)) {
      src <- pick_one(source_tab_dir, "^mouse_marker_dotplot_source_data_.*\\.csv$")
      if (is.na(src)) src <- pick_one(source_tab_dir, "^mouse_marker_dotplot_il6_source_data_.*\\.csv$")
      method <- "Descriptive Seurat DotPlot of canonical markers (% expressed + scaled mean expression). No test."
      return(list(src=src, method=method, stats=stats_file, aux=aux))
    }
    list(src=NA_character_, method="Descriptive (no per-figure source CSV registered).",
         stats=NA_character_, aux=character(0))
  }

  blocks <- character(0)
  for (pdf in pdfs) {
    info <- classify_one_pdf(pdf)
    block <- c(
      sprintf("[FIGURE_FILE]   %s", basename(pdf)),
      sprintf("  source_data : %s", if (is.na(info$src) || !nzchar(info$src)) "N/A" else rel_path(info$src)),
      sprintf("  stat_method : %s", info$method),
      sprintf("  stat_values : %s", if (is.na(info$stats) || !nzchar(info$stats)) "N/A (descriptive figure)" else rel_path(info$stats))
    )
    if (length(info$aux) > 0 && any(!is.na(info$aux) & nzchar(info$aux))) {
      aux_clean <- info$aux[!is.na(info$aux) & nzchar(info$aux)]
      block <- c(block, sprintf("  aux_files   : %s", paste(vapply(aux_clean, rel_path, ""), collapse = " | ")))
    }
    block <- c(block, "  ----")
    blocks <- c(blocks, block)
  }

  header <- c(
    "============================================================",
    "MOUSE STEP5 - FIGURE -> SOURCE DATA & STATISTICS MANIFEST",
    sprintf("Generated: %s", format(Sys.time(), "%Y-%m-%d %H:%M:%S %Z")),
    sprintf("Timestamp tag: %s", timestamp_tag),
    sprintf("Output root  : %s", normalizePath(out_root, winslash = "/", mustWork = FALSE)),
    "Paths below are relative to the output root.",
    "============================================================",
    ""
  )
  out_path <- file.path(fig_dir, sprintf("FIGURE_DATA_STAT_MANIFEST_%s.txt", timestamp_tag))
  writeLines(c(header, blocks), con = out_path)
  invisible(out_path)
}
