plot_score_and_save <- function(df, out_pdf, y_label = "AUC score", title = NULL, show_stats = TRUE){
  pp <- plot_score_single_panel(
    data = df,
    y_var = "score",
    title = title,
    y_label = y_label,
    axis_title_size = 23,
    axis_text_size  = 23,
    show_stats = show_stats
  )
  save_plot_pdf(pp$plot, out_pdf, width = 15.5, height = 8.5, units = "cm")
  if (isTRUE(show_stats) && !is.null(pp$test_stats)) {
    score_mixed_test_tables[[length(score_mixed_test_tables) + 1L]] <<- data.frame(
      plot_file = basename(out_pdf),
      Celltype_use = paste(unique(df$Celltype_use), collapse = ";"),
      feature_set = paste(unique(df$feature_set), collapse = ";"),
      pp$test_stats,
      stringsAsFactors = FALSE
    )
    ts <- pp$test_stats
    ct_str <- paste(unique(df$Celltype_use), collapse = ";")
    ft_str <- paste(unique(df$feature_set), collapse = ";")
    prior_d <- get_prior_direction(ct_str, ft_str)
    obs_d <- sign(ts$effect_estimate[1])
    register_main_p(
      plot_file = basename(out_pdf),
      celltype = ct_str,
      feature_set = ft_str,
      p_value = pp$p_value,
      test_method = "cell-level GLMM with animal random intercept",
      effect_metric = ts$effect_metric[1],
      effect_estimate = ts$effect_estimate[1],
      effect_se = ts$effect_se[1],
      effect_ci_low = ts$effect_ci_low[1],
      effect_ci_high = ts$effect_ci_high[1],
      prior_direction = prior_d,
      observed_direction = obs_d,
      direction_match = !is.na(prior_d) && !is.na(obs_d) &&
        (prior_d == 0 || sign(prior_d) == sign(obs_d))
    )
  }
  invisible(pp)
}

