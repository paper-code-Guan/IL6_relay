# ---------------------------------------------------------------------------
# P[Neu] interaction test.
# Primary inference uses a binomial mixed-effects model with a random animal
# intercept:
#   positive ~ Group * Celltype_use + (1 | Patient)
# The interaction term tests whether the ExN-vs-InN IL-6+ probability contrast
# shifts between Syn-control and Syn-let-7b KO. An animal-level Wilcoxon test on
# within-animal Delta = p_ExN - p_InN is retained as a transparent sensitivity
# analysis. The visualization below shows group means of animal-level IL-6+
# proportions, so the plotted units and sensitivity test both derive from
# animal-level summaries.
# ---------------------------------------------------------------------------
interaction_cell_df <- bind_rows(lapply(c("ExcitNeu", "InhibNeu"), function(ct_) {
  read_score_table(ct_, "IL6", keep_cols = c("Group", "Patient", "positive")) %>%
    mutate(
      Group = factor(normalize_mouse_group(Group), levels = display_levels),
      Celltype_use = ct_
    ) %>%
    filter(Group %in% display_levels)
}))
interaction_mixed_test <- mixed_binary_interaction_test(interaction_cell_df)

