      primary_warning_flag = TRUE,
      n_cells = nrow(df),
      n_patients = length(unique(df$Patient)),
      stringsAsFactors = FALSE
    ))
  }

  fit_res <- fit_glmmTMB_with_warnings(
    glmmTMB::glmmTMB(.y ~ Group + (1 | Patient), data = df, family = gaussian())
  )
  eff <- extract_glmmTMB_effect(fit_res$fit, "^Group")
  data.frame(
    primary_method = "glmmTMB_gaussian_random_patient",
    primary_p = eff$p_value,
    effect_metric = "mean_diff_score",
    effect_estimate = eff$estimate,
    effect_se = eff$se,
    effect_ci_low = eff$ci_low,
    effect_ci_high = eff$ci_high,
    primary_warning = fit_res$warning,
    primary_error = fit_res$error,
    primary_warning_flag = fit_res$warning_flag,
    n_cells = nrow(df),
    n_patients = length(unique(df$Patient)),
    stringsAsFactors = FALSE
  )
}

