# =========================================================
# Mouse step5: post-processing & final plotting (AUCell-based)
#
# Cohort:
#   Syn-let-7b KO vs Syn-control mouse cortex snRNA-seq, with main
#   cell-type framework adapted by data availability:
#     - main3 fallback : ExcitNeu / InhibNeu / Ast
#     - main4 (default): main3 + Mic (when microglia pass the
#                        per-group cell-count threshold)
#     - main5          : main4 + OL (when oligodendrocytes are present)
#   Animal identity is taken from `orig.ident`.
#
# Expected input:
#   1) Annotated mouse Seurat object; force a specific RDS via:
#        export SEURAT_RDS_PATH=/path/to/mouse_annotated.rds
#   2) Formal AUCell output directory generated by 04_aucell_scoring.R.
#      Auto-detects newest under the project's results directory, or:
#        export MOUSE_RESULT_ROOT=/path/to/<run_dir>
#
# Figure outputs (Mic / OL gated by data availability):
#   1)  Celltype UMAP by class                              (Fig1a)
#   2)  Cell-class counts barplot                           (Fig1b)
#   3)  Cell-class composition donut                        (Fig1c)
#   4)  Marker DotPlot (canonical markers; IL6 row removed) (Fig1d)
#   5)  AUCell-positive IL6 UMAP, main CTs                  (Fig4a)
#   6)  AUCell-positive IL6 UMAP, all CTs                   (Fig4b)
#   7)  IL6 raw-count positive UMAP                          (Fig4c)
#   8)  AUCell IL6+ composition donut, main CTs              (Fig5)
#   9)  Per-CT IL6 / GFAP / AIF1 score plots                 (with_stats + no_stats)
#   10) Per-CT IL6 / GFAP / AIF1 positive-proportion plots   (with_stats + no_stats)
#   11) MSigDB Hallmark IL6/JAK/STAT3 module score plots     (per CT)
#   12) IL6+ proportion grouped heatmap (animal-mean)        (CTR / Pooled / KO)
#   13) Excitatory-vs-inhibitory IL6+ proportion interaction
#   14) IL6 forest plot (single-gene + module panels)
#
# Statistical methods (only two inferential families):
#   * GLMM (glmmTMB) with random per-animal intercept (orig.ident):
#       - score path     : gaussian, AUC ~ Group + (1|Patient)
#       - proportion path: binomial, positive ~ Group + (1|Patient)
#       - interaction    : positive ~ Group * Celltype_use + (1|Patient)
#   * Animal-level Wilcoxon rank-sum on per-animal summaries:
#       - PRIMARY only for excitatory-vs-inhibitory interaction
#         (cell-level GLMM as sensitivity)
#   Multiplicity controlled via Benjamini-Hochberg FDR within each
#   cell-type family. Fold change estimated via Haldane-Anscombe
#   pseudocount.
#
# Notes:
#   - Single-gene cytokine positivity (IL6, GFAP, AIF1) follows the
#     rank-and-detection rule from step4: positive = (AUC > 0 at extended
#     top window aucMaxRank=0.10*G) OR (raw count > 0). Multi-gene module
#     positivity uses AUCell's selected threshold on the default top
#     window (aucMaxRank=0.05*G).
#   - Score and proportion plots are exported in two versions:
#       *_with_stats_*.pdf : Mean and GLMM P annotated
#       *_no_stats_*.pdf   : no annotation
#   - GFAP and AIF1 AUC scores are computed on-demand within the target
#     cell type only (no whole-tissue rebuild).
# =========================================================

