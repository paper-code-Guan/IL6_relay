match_genes_case_insensitive <- function(genes, seu) {
  rn    <- rownames(seurat_get_layer(seu, assay = "RNA", layer = "counts"))
  rn_up <- toupper(rn)
  want  <- unique(toupper(genes))

  hits <- vapply(
    want,
    function(g) {
      idx <- which(rn_up == g)
      if (length(idx) > 0) rn[idx[1]] else NA_character_
    },
    FUN.VALUE = character(1)
  )

  missing_genes <- want[is.na(hits)]
  if (length(missing_genes) > 0) {
    cat("The following genes were not found in the dataset:\n",
        paste(missing_genes, collapse = ", "), "\n")
  }

  unique(stats::na.omit(hits))
}

