canonicalize_mouse_ct <- function(v){
  x  <- trimws(as.character(v))
  xl <- tolower(x)

  out <- rep(NA_character_, length(x))

  out[xl %in% c("ast","astro","astrocyte","astrocytes")] <- "Ast"
  out[xl %in% c("excitneu","exn","excitatory neuron","excitatory neurons",
                "glutamatergic neuron","glutamatergic neurons")] <- "ExcitNeu"
  out[xl %in% c("inhibneu","inn","inhibitory neuron","inhibitory neurons",
                "gabaergic neuron","gabaergic neurons")] <- "InhibNeu"

  out[xl %in% c("ol","oligo","oligodendrocyte","oligodendrocytes")] <- "OL"
  out[xl %in% c("opc","opcs","oligodendrocyte precursor cells")] <- "OPC"
  out[xl %in% c("mic","micro","microglia")] <- "Mic"
  out[xl %in% c("endo","endothelial","endothelial cell","endothelial cells")] <- "Endo"
  out[xl %in% c("peri","pericyte","pericytes")] <- "Pericytes"
  out[xl %in% c("lept","lepts","leptomeningeal","leptomeningeal cell","leptomeningeal cells",
                "lmc","lmcs")] <- "Leptomeningeal"

  out[is.na(out) & x %in% c("Ast","ExcitNeu","InhibNeu","OL","OPC","Mic","Endo","Pericytes","Leptomeningeal")] <-
    x[is.na(out) & x %in% c("Ast","ExcitNeu","InhibNeu","OL","OPC","Mic","Endo","Pericytes","Leptomeningeal")]

  out
}

