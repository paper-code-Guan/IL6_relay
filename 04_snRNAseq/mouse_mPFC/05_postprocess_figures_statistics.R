build_paper_manifest_subset_mouse <- function(full_manifest_path,
                                              paper_pdf_dir,
                                              paper_manifest_path,
                                              paper_source_basenames,
                                              rename_map) {
  if (!file.exists(full_manifest_path)) {
    warning("Full manifest not found; mouse paper manifest subset skipped.")
    return(invisible(NULL))
  }
  if (!length(paper_source_basenames)) {
    warning("No PDFs copied to figures_paper/; mouse paper manifest subset skipped.")
    return(invisible(NULL))
  }
  full_lines <- readLines(full_manifest_path, warn = FALSE)

  out_blocks <- character(0)
  in_block   <- FALSE
  keep_block <- FALSE
  cur_block  <- character(0)
  for (line in full_lines) {
    if (grepl("^\\[FIGURE_FILE\\]", line)) {
      if (in_block && keep_block) out_blocks <- c(out_blocks, cur_block)
      pdf_name   <- trimws(sub("^\\[FIGURE_FILE\\]\\s+", "", line))
      keep_block <- pdf_name %in% paper_source_basenames
      # Rewrite the [FIGURE_FILE] header to the renamed figures_paper name
      if (keep_block) {
        new_pdf_name <- pdf_name
        for (.os in names(rename_map)) {
          .ts <- rename_map[[.os]]
          .pat <- paste0("^mouse_", .os, "(_[0-9]+\\.pdf)$")
          if (grepl(.pat, pdf_name)) {
            new_pdf_name <- sub(.pat, paste0(.ts, "\\1"), pdf_name)
            break
          }
        }
        line <- sprintf("[FIGURE_FILE]   %s", new_pdf_name)
      }
      cur_block  <- line
      in_block   <- TRUE
    } else if (in_block) {
      cur_block <- c(cur_block, line)
      if (grepl("^\\s*----\\s*$", line)) {
        if (keep_block) out_blocks <- c(out_blocks, cur_block)
        in_block   <- FALSE
        keep_block <- FALSE
        cur_block  <- character(0)
      }
    }
  }
  if (in_block && keep_block) out_blocks <- c(out_blocks, cur_block)

  out_blocks <- gsub("(:\\s+)(tables/)", "\\1../\\2", out_blocks)

  ts <- format(Sys.time(), "%Y-%m-%d %H:%M:%S %Z")
  banner <- c(
    "============================================================",
    "MOUSE STEP5 - PAPER FIGURE SUBSET",
    sprintf("Generated: %s", ts),
    sprintf("Timestamp tag: %s", timestamp_tag),
    "",
    "Subset of full manifest, filtered to figures included in the",
    "published manuscript, renamed with figure-number prefixes",
    "(3f_, 3g_, 3h_, 4a_, 4b_, s8a_ ... s8h_, s8ei_). See",
    sprintf("  ../figures/FIGURE_DATA_STAT_MANIFEST_%s.txt", timestamp_tag),
    "for the full pipeline output (figures + tables/CSV references).",
    "Paths below are relative to this file (figures_paper/).",
    "============================================================",
    ""
  )

  writeLines(c(banner, out_blocks), con = paper_manifest_path)
  invisible(paper_manifest_path)
}

