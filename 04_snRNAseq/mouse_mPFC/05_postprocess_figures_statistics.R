# 15b) IL6+ proportion grouped heatmap (columns = cell types; rows =
#     Syn-control / Syn-let-7b KO / log2FC).
#
#     The first two rows are neutral light-grey animal-level mean-rate
#     numeric tiles so the raw group-wise percentages remain visually
#     readable without implying a colour-encoded effect size. A third
#     log2FC row is added below the KO row, where log2FC is
#     log2(KO / Syn-control) computed from the animal-level mean IL6+
#     proportions with a small floor only to stabilise zero values.
#     The diverging blue-white-red row encodes direction and magnitude of
#     change, while the colourbar reports only the log2FC scale.
# ---------------------------------------------------------
heatmap_grouped_short_map <- c(
  "Ast"      = "Astro",
  "ExcitNeu" = "ExtNeu",
  "InhibNeu" = "InbNeu",
  "Mic"      = "MiGlia",
  "OL"       = "Oligo"
)
# Heatmap row order top-to-bottom: ExtNeu, InbNeu, Astro, MiGlia (if Mic
# available), Oligo (if oligo_avail$has_oligo). When both are present this
# yields 5 rows -> 15 cells, matching the request to put Oligo below MiGlia.
heatmap_row_order_top_to_bottom <- c("ExcitNeu", "InhibNeu", "Ast")
if (mic_avail$has_mic)    heatmap_row_order_top_to_bottom <- c(heatmap_row_order_top_to_bottom, "Mic")
if (oligo_avail$has_oligo) heatmap_row_order_top_to_bottom <- c(heatmap_row_order_top_to_bottom, "OL")

heatmap_grouped_long <- bind_rows(lapply(heatmap_row_order_top_to_bottom, function(ct){
  df_ct <- read_score_table(ct, "IL6", keep_cols = c("Group", "Patient", "positive"))
  df_ct$positive <- as.logical(df_ct$positive)
  df_ct <- df_ct %>% filter(Group %in% display_levels)

  donor_prop <- df_ct %>%
    group_by(Group, Patient) %>%
    summarise(n_cells = dplyr::n(),
              n_pos   = sum(positive, na.rm = TRUE),
              prop    = ifelse(n_cells > 0, n_pos / n_cells, NA_real_),
              .groups = "drop")

  ctr_dp <- donor_prop %>% filter(Group == display_levels[1])
  ko_dp  <- donor_prop %>% filter(Group == display_levels[2])

  ctr_rate <- if (nrow(ctr_dp) > 0) mean(ctr_dp$prop, na.rm = TRUE) else NA_real_
  ko_rate  <- if (nrow(ko_dp)  > 0) mean(ko_dp$prop,  na.rm = TRUE) else NA_real_

  data.frame(
    Celltype_use         = ct,
    Celltype_label_short = unname(heatmap_grouped_short_map[ct]),
    Group_col            = c("Syn-control", "Syn-let-7b KO"),
    n_animals             = c(nrow(ctr_dp), nrow(ko_dp)),
    n_cells              = c(sum(ctr_dp$n_cells), sum(ko_dp$n_cells)),
    n_positive           = c(sum(ctr_dp$n_pos),  sum(ko_dp$n_pos)),
    proportion           = c(ctr_rate, ko_rate),
    stringsAsFactors     = FALSE
  )
}))

heatmap_grouped_long <- heatmap_grouped_long %>%
