safe_file_id <- function(x){
  x <- gsub("[^A-Za-z0-9]+", "_", x)
  x <- gsub("_+", "_", x)
  x <- gsub("^_|_$", "", x)
  x
}

format_p <- function(p){
  if (is.na(p)) return("P = NA")
  if (!is.finite(p)) return("P = NA")
  if (p == 0) return("P < 2.2e-16")

  if (p < 0.01) {
    return(paste0("P = ", format(p, scientific = TRUE, digits = 2)))
  } else {
    return(sprintf("P = %.4f", p))
  }
}

format_p_method <- function(p, method = "GLMM"){
  sub("^P", paste0(method, " P"), format_p(p))
}

fit_glmmTMB_with_warnings <- function(expr){
  warning_messages <- character()
  fit <- tryCatch(
    withCallingHandlers(
      expr,
      warning = function(w) {
        warning_messages <<- c(warning_messages, conditionMessage(w))
        invokeRestart("muffleWarning")
      }
    ),
    error = function(e) e
  )
  warning_text <- paste(unique(warning_messages), collapse = " | ")
  error_text <- if (inherits(fit, "error")) conditionMessage(fit) else ""
  diagnostic_text <- paste(warning_text, error_text)
  diagnostic_flag <- grepl(
    "convergence|non-positive-definite|singular|false convergence|hessian|nan|failed|not positive definite",
    diagnostic_text,
    ignore.case = TRUE
  ) || nzchar(error_text)
  list(
    fit = fit,
    warning = warning_text,
    error = error_text,
    warning_flag = diagnostic_flag
  )
}

extract_glmmTMB_p <- function(fit, term_regex){
  if (inherits(fit, "error")) return(NA_real_)
  coef_tab <- tryCatch(as.data.frame(summary(fit)$coefficients$cond), error = function(e) NULL)
  if (is.null(coef_tab) || !nrow(coef_tab)) return(NA_real_)
  p_col <- grep("^Pr\\(", colnames(coef_tab), value = TRUE)[1]
  if (is.na(p_col)) return(NA_real_)
  term <- grep(term_regex, rownames(coef_tab), value = TRUE)[1]
  if (is.na(term)) return(NA_real_)
  as.numeric(coef_tab[term, p_col])
}

extract_glmmTMB_effect <- function(fit, term_regex, ci_level = 0.95){
  na_out <- list(
    estimate = NA_real_,
    se = NA_real_,
    ci_low = NA_real_,
    ci_high = NA_real_,
    p_value = NA_real_,
    term = NA_character_
  )
  if (inherits(fit, "error") || is.null(fit)) return(na_out)
  coef_tab <- tryCatch(as.data.frame(summary(fit)$coefficients$cond), error = function(e) NULL)
  if (is.null(coef_tab) || !nrow(coef_tab)) return(na_out)
  p_col <- grep("^Pr\\(", colnames(coef_tab), value = TRUE)[1]
  est_col <- "Estimate"
  se_col <- "Std. Error"
  if (!all(c(est_col, se_col, p_col) %in% colnames(coef_tab))) return(na_out)
  term <- grep(term_regex, rownames(coef_tab), value = TRUE)[1]
  if (is.na(term)) return(na_out)
  est <- as.numeric(coef_tab[term, est_col])
  se <- as.numeric(coef_tab[term, se_col])
  z <- qnorm(1 - (1 - ci_level) / 2)
  list(
    estimate = est,
    se = se,
    ci_low = est - z * se,
    ci_high = est + z * se,
    p_value = as.numeric(coef_tab[term, p_col]),
    term = term
  )
}

detect_microglia_availability <- function(obj,
                                          group_levels = c("Syn-control", "Syn-let-7b KO"),
                                          target_ct = "Mic",
                                          min_cells_per_group = pipeline_threshold_min_mic_cells_per_group,
                                          min_donors_per_group = pipeline_threshold_min_mic_donors_per_group){
  na_out <- function(reason){
    list(
      has_mic = FALSE,
      decision_reason = reason,
      n_mic_cells_ctrl = 0L,
      n_mic_cells_case = 0L,
      n_donors_with_mic_ctrl = 0L,
      n_donors_with_mic_case = 0L,
      threshold_min_cells = min_cells_per_group,
      threshold_min_donors = min_donors_per_group,
      group_levels_used = paste(group_levels, collapse = ", "),
      target_ct = target_ct
    )
  }
  if (!"Celltype_use" %in% colnames(obj@meta.data)) return(na_out("Celltype_use column missing"))
  if (!target_ct %in% obj$Celltype_use) return(na_out(sprintf("No '%s' cells in Celltype_use", target_ct)))
  if (!"Group" %in% colnames(obj@meta.data)) return(na_out("Group column missing"))
  if (!"orig.ident" %in% colnames(obj@meta.data)) return(na_out("orig.ident missing"))

  mic_meta <- obj@meta.data[as.character(obj$Celltype_use) == target_ct, , drop = FALSE]
  ctrl <- group_levels[1]
  case <- group_levels[2]
  n_cells_ctrl <- sum(mic_meta$Group == ctrl, na.rm = TRUE)
  n_cells_case <- sum(mic_meta$Group == case, na.rm = TRUE)
  n_don_ctrl <- length(unique(as.character(mic_meta$orig.ident[mic_meta$Group == ctrl])))
  n_don_case <- length(unique(as.character(mic_meta$orig.ident[mic_meta$Group == case])))

  pass <- (n_cells_ctrl >= min_cells_per_group &&
             n_cells_case >= min_cells_per_group &&
             n_don_ctrl >= min_donors_per_group &&
             n_don_case >= min_donors_per_group)
  reason <- if (pass) {
    sprintf("Mic available: cells %d/%d (%s/%s), donors %d/%d, thresholds %d cells & %d donors per group",
            n_cells_ctrl, n_cells_case, ctrl, case, n_don_ctrl, n_don_case,
            min_cells_per_group, min_donors_per_group)
  } else {
    sprintf("Mic insufficient (need >=%d cells AND >=%d donors per group): cells %d/%d, donors %d/%d",
            min_cells_per_group, min_donors_per_group,
            n_cells_ctrl, n_cells_case, n_don_ctrl, n_don_case)
  }

  out <- list(
    has_mic = pass,
    decision_reason = reason,
    n_mic_cells_ctrl = n_cells_ctrl,
    n_mic_cells_case = n_cells_case,
    n_donors_with_mic_ctrl = n_don_ctrl,
    n_donors_with_mic_case = n_don_case,
    threshold_min_cells = min_cells_per_group,
    threshold_min_donors = min_donors_per_group,
    group_levels_used = paste(group_levels, collapse = ", "),
    target_ct = target_ct
  )
  if (!pass) {
    hint <- if (n_cells_ctrl < min_cells_per_group || n_cells_case < min_cells_per_group) {
      sprintf("  Cell-count threshold not met (need >=%d per group, observed %d/%d).",
              min_cells_per_group, n_cells_ctrl, n_cells_case)
    } else {
      sprintf("  Animal-count threshold not met. Mic appears in only %d/%d animals per group (need %d).",
              min(n_don_ctrl, n_don_case), min_donors_per_group, min_donors_per_group)
    }
    out$hint <- hint
  }
  out
}

# Oligodendrocyte availability gate (mirrors detect_microglia_availability).
# Used to decide whether OL is included in the per-CT figure panels (IL6
# score, IL6 positive proportion, MSigDB module score) as an additional
# cell type beyond the cts_main set used elsewhere.
pipeline_threshold_min_oligo_cells_per_group  <- 50
pipeline_threshold_min_oligo_donors_per_group <- 3
detect_oligo_availability <- function(obj,
                                      group_levels = c("Syn-control", "Syn-let-7b KO"),
                                      target_ct = "OL",
                                      min_cells_per_group  = pipeline_threshold_min_oligo_cells_per_group,
                                      min_donors_per_group = pipeline_threshold_min_oligo_donors_per_group){
  na_out <- function(reason){
    list(
      has_oligo = FALSE,
      decision_reason = reason,
      n_oligo_cells_ctrl = 0L, n_oligo_cells_case = 0L,
      n_donors_with_oligo_ctrl = 0L, n_donors_with_oligo_case = 0L,
      threshold_min_cells = min_cells_per_group,
      threshold_min_donors = min_donors_per_group,
      group_levels_used = paste(group_levels, collapse = ", "),
      target_ct = target_ct
    )
  }
  if (!"Celltype_use" %in% colnames(obj@meta.data)) return(na_out("Celltype_use column missing"))
  ct_chars <- as.character(obj$Celltype_use)
  if (!target_ct %in% ct_chars) return(na_out(sprintf("No '%s' cells in Celltype_use", target_ct)))
  if (!"Group" %in% colnames(obj@meta.data)) return(na_out("Group column missing"))
  # Mouse Seurat objects use orig.ident as the animal identifier.
  if (!"orig.ident" %in% colnames(obj@meta.data)) return(na_out("orig.ident column missing"))

  ol_meta <- obj@meta.data[ct_chars == target_ct, , drop = FALSE]
  ctrl <- group_levels[1]; case <- group_levels[2]
  n_cells_ctrl <- sum(ol_meta$Group == ctrl, na.rm = TRUE)
  n_cells_case <- sum(ol_meta$Group == case, na.rm = TRUE)
  n_don_ctrl   <- length(unique(as.character(ol_meta$orig.ident[ol_meta$Group == ctrl])))
  n_don_case   <- length(unique(as.character(ol_meta$orig.ident[ol_meta$Group == case])))

  pass <- (n_cells_ctrl >= min_cells_per_group &&
             n_cells_case >= min_cells_per_group &&
             n_don_ctrl   >= min_donors_per_group &&
             n_don_case   >= min_donors_per_group)
  reason <- if (pass)
    sprintf("Oligo available: cells %d/%d (%s/%s), animals %d/%d, thresholds %d cells and %d animals per group",
            n_cells_ctrl, n_cells_case, ctrl, case, n_don_ctrl, n_don_case,
            min_cells_per_group, min_donors_per_group)
  else
    sprintf("Oligo insufficient (need >=%d cells and >=%d animals per group): cells %d/%d, animals %d/%d",
            min_cells_per_group, min_donors_per_group,
            n_cells_ctrl, n_cells_case, n_don_ctrl, n_don_case)
  out <- list(
    has_oligo = pass, decision_reason = reason,
    n_oligo_cells_ctrl = n_cells_ctrl, n_oligo_cells_case = n_cells_case,
    n_donors_with_oligo_ctrl = n_don_ctrl, n_donors_with_oligo_case = n_don_case,
    threshold_min_cells = min_cells_per_group,
    threshold_min_donors = min_donors_per_group,
    group_levels_used = paste(group_levels, collapse = ", "),
    target_ct = target_ct
  )
  if (!pass){
    hint <- if (n_cells_ctrl < min_cells_per_group || n_cells_case < min_cells_per_group)
      sprintf("  Oligo cell-count threshold not met (need >=%d per group, observed %d/%d).",
              min_cells_per_group, n_cells_ctrl, n_cells_case)
    else
      sprintf("  Oligo animal-count threshold not met (need >=%d per group, observed %d/%d).",
              min_donors_per_group, n_don_ctrl, n_don_case)
    out$hint <- hint
  }
  out
}

compute_fold_change_HA <- function(per_animal,
                                   ctrl_level = "Syn-control",
                                   case_level = "Syn-let-7b KO",
                                   pseudocount = 0.5){
  agg <- per_animal %>%
    group_by(Group) %>%
    summarise(
      n_pos_pool = sum(n_positive, na.rm = TRUE),
      n_total_pool = sum(n_total, na.rm = TRUE),
      .groups = "drop"
    ) %>%
    mutate(
      rate_HA = (n_pos_pool + pseudocount) / (n_total_pool + 2 * pseudocount)
    )
  ctrl_rate <- agg$rate_HA[agg$Group == ctrl_level]
  case_rate <- agg$rate_HA[agg$Group == case_level]
  list(
    ctrl_rate_HA = ctrl_rate,
    case_rate_HA = case_rate,
    fold_change = if (length(ctrl_rate) && length(case_rate)) case_rate / ctrl_rate else NA_real_,
    log2_fc = if (length(ctrl_rate) && length(case_rate)) log2(case_rate / ctrl_rate) else NA_real_,
    pseudocount_method = sprintf("Haldane-Anscombe-%.2f", pseudocount)
  )
}

