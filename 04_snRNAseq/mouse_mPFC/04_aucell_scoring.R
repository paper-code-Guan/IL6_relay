canonicalize_mouse_ct <- function(v) {
  x  <- trimws(as.character(v))
  xl <- tolower(x)
  out <- rep(NA_character_, length(x))

  out[xl %in% c("ast", "astro", "astrocyte", "astrocytes")] <- "Ast"
  out[xl %in% c("excitneu", "exn", "glutamatergic neuron", "glutamatergic neurons",
                "excitatory neuron", "excitatory neurons")] <- "ExcitNeu"
  out[xl %in% c("inhibneu", "inn", "gabaergic neuron", "gabaergic neurons",
                "inhibitory neuron", "inhibitory neurons")] <- "InhibNeu"
  out[xl %in% c("ol", "oligo", "oligodendrocyte", "oligodendrocytes")] <- "OL"
  out[xl %in% c("opc", "opcs", "oligodendrocyte precursor cells")] <- "OPC"
  out[xl %in% c("mic", "micro", "microglia")] <- "Mic"
  out[xl %in% c("endo", "endothelial", "endothelial cell", "endothelial cells")] <- "Endo"
  out[xl %in% c("peri", "pericyte", "pericytes")] <- "Pericytes"

  out[
    xl %in% c(
      "lept", "lepts", "leptomeningeal", "leptomeningeal cell", "leptomeningeal cells",
      "lmc", "lmcs", "vlmc", "vlmcs", "vascular leptomeningeal cell",
      "vascular leptomeningeal cells", "vascular and leptomeningeal cell",
      "vascular and leptomeningeal cells"
    ) |
      grepl("^lept|lepto|mening|vlmc", xl)
  ] <- "Leptomeningeal"

  already_standard <- x %in% c(
    "Ast", "ExcitNeu", "InhibNeu", "OL", "OPC", "Mic", "Endo", "Pericytes", "Leptomeningeal"
  )
  out[is.na(out) & already_standard] <- x[is.na(out) & already_standard]

  out
}

