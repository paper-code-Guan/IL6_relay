# =========================================================
# Mouse formal analysis (AUCell-based)
# IL6 single-gene score and IL-6-associated signaling module score
#
# Workflow per cell type:
#   1) subset Seurat object by curated cell type
#   2) extract RNA raw count matrix
#   3) build within-cell-type rankings via AUCell::AUCell_buildRankings
#   4) compute AUC scores via AUCell::AUCell_calcAUC
#   5) determine positivity via AUCell::AUCell_exploreThresholds (default settings)
#
# Important interpretation:
#   - Positivity rule for both single-gene and multi-gene signatures:
#       positive = AUC score > AUCell-selected threshold
#   - The AUCell threshold is selected by the package's default logic
#     (smallestPopPercent = 0.25; candidate methods include minimumDens,
#     L_k2, R_k3, Global_k1; selection is data-driven and unmodified).
#
# Run example:
#   Rscript --vanilla 04_aucell_scoring.R
# =========================================================

