score_file_header_cache <- new.env(parent = emptyenv())

find_score_file <- function(ct_name, feature_name, required = TRUE) {
  ct_aliases <- ct_name

  feature_aliases <- feature_name

  ct_ids <- safe_file_id(ct_aliases)
  feature_ids <- safe_file_id(feature_aliases)
  pattern_grid <- expand.grid(ct_id = ct_ids, feature_id = feature_ids, stringsAsFactors = FALSE)
  patterns <- unique(unlist(lapply(seq_len(nrow(pattern_grid)), function(i) {
    ct_id <- pattern_grid$ct_id[i]
    feature_id <- pattern_grid$feature_id[i]
    c(
      sprintf("^scores_%s_%s_.*\\.csv$", ct_id, feature_id),
      sprintf("^%s_%s_scores_.*\\.csv$", ct_id, feature_id)
    )
  }), use.names = FALSE))

  ff <- unique(unlist(lapply(tab_search_dirs, function(td) {
    unique(unlist(lapply(patterns, function(pat) {
      list.files(td, pattern = pat, full.names = TRUE, recursive = TRUE)
    }), use.names = FALSE))
  }), use.names = FALSE))

  if (!length(ff)) {
    msg <- paste0(
      "No score file found for: ", ct_name, " / ", feature_name,
      "\nPatterns:\n  ", paste(patterns, collapse = "\n  "),
      "\nSearched directories:\n  ", paste(tab_search_dirs, collapse = "\n  ")
    )
    if (required) stop(msg) else return(character(0))
  }

  if (length(ff) > 1L) {
    ff <- ff[order(file.info(ff)$mtime, decreasing = TRUE)]
    message("Multiple score files found for ", ct_name, " / ", feature_name,
            "; using the newest one:\n  ", ff[1])
  }

  ff[1]
}
get_positive <- function(df) {
  cn <- colnames(df)

  positive_col <- c("positive", "positive_mask", "aucell_mask")
  positive_col <- positive_col[positive_col %in% cn][1]

  if (!is.na(positive_col)) {
    return(as.logical(df[[positive_col]]))
  }

  stop("Cannot resolve positive-cell column. Columns are:\n",
       paste(cn, collapse = ", "))
}

read_score_table <- function(ct_name, feature_name, keep_cols = NULL) {
  f <- find_score_file(ct_name, feature_name)
  if (is.null(keep_cols)) {
    df <- read.csv(f, stringsAsFactors = FALSE, check.names = FALSE)
  } else {
    header_key <- normalizePath(f, winslash = "/", mustWork = FALSE)
    if (!exists(header_key, envir = score_file_header_cache, inherits = FALSE)) {
      assign(
        header_key,
        names(readr::read_csv(f, n_max = 0, show_col_types = FALSE, progress = FALSE)),
        envir = score_file_header_cache
      )
    }
    file_cols <- get(header_key, envir = score_file_header_cache, inherits = FALSE)
    cols_needed <- unique(c(
      "cell", "Group", "Patient", "orig.ident", "Celltypes_raw",
      "Celltype_use", "Celltype_label", "feature_set",
      "score", "score_default_window", "expr_count_proxy",
      "threshold_selected", "threshold_method", "K_top_used",
      "positive", "positive_mask", "aucell_mask", "rank_mask", "detection_mask",
      "detection_used",
      keep_cols
    ))
    col_select <- intersect(file_cols, cols_needed)
    df <- as.data.frame(readr::read_csv(
      f,
      show_col_types = FALSE,
      progress = FALSE,
      col_select = tidyselect::all_of(col_select)
    ))
  }
  stopifnot("cell column missing in score table." = "cell" %in% colnames(df))

  if (!"Group" %in% colnames(df)) stop("Group column missing in score table: ", f)
  df$Group <- factor(normalize_group(df$Group), levels = display_levels)
  if (!"Patient" %in% colnames(df)) {
    if ("orig.ident" %in% colnames(df)) {
      df$Patient <- as.character(df$orig.ident)
    } else {
      stop("Patient column missing in score table: ", f)
    }
  } else {
    df$Patient <- as.character(df$Patient)
  }
  # HBCC defensive (CRITICAL): if upstream step4 wrote Patient from
  # `orig.ident` and `orig.ident` is a degenerate literal (e.g. all cells
  # == "Donor"), Patient collapses to a single value and every donor-
  # aggregated downstream stat (GLMM, Wilcoxon, donor-mean heatmap, fold
  # change, forest plot, interaction plot) becomes broken (n_donors=1).
  # Reconstruct Patient from the cell-barcode prefix
  # ('<DonorID>-<lane>-<barcode>-<rep>') so already-computed step4 score
  # CSVs do not need to be regenerated.
  if (length(unique(stats::na.omit(df$Patient))) <= 1L && "cell" %in% colnames(df)) {
    bc_donor <- sub("-.*", "", as.character(df$cell))
    if (length(unique(bc_donor)) > 1L) {
      message(sprintf(
        "[read_score_table] %s: degenerate Patient (n_unique=%d) -> reconstructed from cell-barcode prefix (n_unique=%d).",
        basename(f),
        length(unique(stats::na.omit(df$Patient))), length(unique(bc_donor))
      ))
      df$Patient <- bc_donor
    }
  }

  # ---- HBCC donor inclusion filter (paper methods) ----
  # Stage 1: restrict to donors that pass age + comorbid (CTR-only) filter.
  # Stage 2: drop donors whose per-CT cell count is below threshold.
  # Both stages are no-ops when hbcc_donor_filter_active = FALSE.
  if (isTRUE(hbcc_donor_filter_active) && !is.null(hbcc_keep_donors)) {
    df <- df[as.character(df$Patient) %in% hbcc_keep_donors, , drop = FALSE]
  }
  if (isTRUE(hbcc_donor_filter_active) && hbcc_min_cells_per_ct > 0L && nrow(df) > 0L) {
    .n_per_donor <- table(as.character(df$Patient))
    .donors_drop <- names(.n_per_donor)[.n_per_donor < hbcc_min_cells_per_ct]
    if (length(.donors_drop)) {
      .key <- paste(ct_name, feature_name, sep = "__")
      assign(.key, .donors_drop, envir = hbcc_drop_n_cells_log)
      message(sprintf(
        "[read_score_table] %s/%s: drop %d donor(s) with n_cells<%d -> %s",
        ct_name, feature_name, length(.donors_drop), hbcc_min_cells_per_ct,
        paste(.donors_drop, collapse = ",")))
      df <- df[!as.character(df$Patient) %in% .donors_drop, , drop = FALSE]
    }
    rm(.n_per_donor, .donors_drop)
  }

  if (!"score" %in% colnames(df)) {
    stop("'score' column missing in score table; cannot proceed: ", f)
  } else {
    df$score <- as.numeric(df$score)
  }

  if ("threshold_selected" %in% colnames(df)) {
    df$threshold_selected <- suppressWarnings(as.numeric(df$threshold_selected))
  }

  df$positive <- get_positive(df)
  df$Celltype_use <- ct_name
  df$Celltype_label <- pretty_ct(ct_name)
  df$feature_set <- feature_name
  if (!is.null(keep_cols)) {
    keep_final <- unique(c(
      "cell", "Group", "Patient", "orig.ident", "Celltypes_raw",
      "Celltype_use", "Celltype_label", "feature_set",
      "score", "threshold_selected", "threshold_method", "positive",
      keep_cols
    ))
    df <- df[, intersect(keep_final, colnames(df)), drop = FALSE]
  }
  df
}

top_percent_use         <- 0.05  # AUCell aucMaxRank fraction (default top window) for multi-gene module
top_percent_use_single  <- 0.10  # extended top window for single-gene cytokine analysis (Aibar 2017)

resolve_features_ci <- function(symbols, pool_rows) {
  idx <- match(tolower(symbols), tolower(pool_rows))
  res <- ifelse(is.na(idx), NA_character_, pool_rows[idx])
  list(
    found = unique(stats::na.omit(res)),
    missing = unique(symbols[is.na(idx)]),
    mapping = data.frame(
      requested = symbols,
      resolved = unname(res),
      stringsAsFactors = FALSE
    )
  )
}

compute_single_gene_score_df <- function(seu, ct_name, gene_symbol,
                                         top_percent_default = 0.05,
                                         top_percent_single  = 0.10) {
  stopifnot(inherits(seu, "Seurat"))
  stopifnot("Celltype_use missing in Seurat object" = "Celltype_use" %in% colnames(seu@meta.data))
  stopifnot("Group missing in Seurat object" = "Group" %in% colnames(seu@meta.data))

  cells_ct <- rownames(seu@meta.data)[as.character(seu$Celltype_use) == ct_name]
  if (!length(cells_ct)) {
    stop("No cells found for CT: ", ct_name)
  }

  seu_ct <- subset(seu, cells = cells_ct)
  meta_ct <- seu_ct@meta.data

  counts_ct <- seurat_get_layer(seu_ct, assay = "RNA", layer = "counts")

  gene_map <- resolve_features_ci(gene_symbol, rownames(counts_ct))
  genes_found <- gene_map$found
  if (length(genes_found) != 1L) {
    stop("Target single gene not found uniquely: ", gene_symbol,
         "\nFound: ", paste(genes_found, collapse = ", "))
  }

  if (!inherits(counts_ct, "dgCMatrix")) {
    counts_ct <- as(counts_ct, "CsparseMatrix")
  }

  K_top_default <- max(1L, ceiling(top_percent_default * nrow(counts_ct)))
  K_top_single  <- max(1L, ceiling(top_percent_single  * nrow(counts_ct)))

  rankings <- AUCell::AUCell_buildRankings(
    counts_ct,
    plotStats = FALSE,
    verbose = FALSE,
    BPPARAM = BiocParallel::SerialParam()
  )

  gene_set_named <- setNames(list(genes_found), gene_symbol)
  auc_res_default <- AUCell::AUCell_calcAUC(geneSets = gene_set_named, rankings = rankings,
                                            aucMaxRank = K_top_default, verbose = FALSE)
  auc_res_single  <- AUCell::AUCell_calcAUC(geneSets = gene_set_named, rankings = rankings,
                                            aucMaxRank = K_top_single,  verbose = FALSE)

  cells_in_order <- colnames(seu_ct)
  score_vec_default <- as.numeric(AUCell::getAUC(auc_res_default)[gene_symbol, cells_in_order])
  names(score_vec_default) <- cells_in_order
  score_vec_single  <- as.numeric(AUCell::getAUC(auc_res_single )[gene_symbol, cells_in_order])
  names(score_vec_single) <- cells_in_order

  # Primary score uses the extended (single-gene) window, consistent with the
  # rank-and-detection positivity definition.
  score_vec <- score_vec_single

  explore_res <- tryCatch(
    AUCell::AUCell_exploreThresholds(
      auc_res_default,
      plotHist = FALSE,
      smallestPopPercent = 0.25,
      assignCells = TRUE,
      verbose = FALSE
    ),
    error = function(e) {
      message("  AUCell_exploreThresholds failed in compute_single_gene_score_df (",
              ct_name, "/", gene_symbol, "); fallback to Global_k1: ",
              conditionMessage(e))
      NULL
    }
  )

  thr_info <- if (!is.null(explore_res) && !is.null(explore_res[[gene_symbol]])) {
    aucThr <- explore_res[[gene_symbol]]$aucThr
    sel <- as.numeric(aucThr$selected)
    method_name <- "AUCell_default"
    candidates_local <- NULL
    if (!is.null(aucThr$thresholds)) {
      thr_df_df <- as.data.frame(aucThr$thresholds, stringsAsFactors = FALSE)
      thr_col <- if ("threshold" %in% colnames(thr_df_df)) "threshold" else colnames(thr_df_df)[1]
      thr_vals <- suppressWarnings(as.numeric(thr_df_df[[thr_col]]))
      candidates_local <- data.frame(
        method = rownames(thr_df_df),
        threshold = thr_vals,
        stringsAsFactors = FALSE
      )
      if (length(thr_vals) && any(is.finite(thr_vals))) {
        idx <- which.min(abs(thr_vals - sel))
        method_name <- rownames(thr_df_df)[idx]
      }
    }
    if (identical(method_name, "tenPercentOfMax") && !is.null(candidates_local)) {
      gk1_idx <- which(candidates_local$method == "Global_k1")
      if (length(gk1_idx)) {
        gk1_thr <- candidates_local$threshold[gk1_idx[1]]
        if (is.finite(gk1_thr)) {
          sel <- gk1_thr
          method_name <- "Global_k1"
        }
      }
    }
    list(selected = sel, method = method_name)
  } else {
    s <- score_vec_default[is.finite(score_vec_default)]
    sel <- if (length(s) > 1 && stats::sd(s) > 0) mean(s) + 2 * stats::sd(s) else max(s, 0) + .Machine$double.eps
    list(selected = sel, method = "Global_k1_fallback")
  }

  aucell_mask <- score_vec_default > thr_info$selected
  aucell_mask[!is.finite(score_vec_default)] <- FALSE

  # Single-gene rank-and-detection positivity using the extended window:
  #   positive = (AUC > 0 at extended window, i.e., rank <= K_top_single) OR
  #              (raw count > 0)
  expr_count_proxy <- as.numeric(counts_ct[genes_found, cells_in_order, drop = TRUE])
  names(expr_count_proxy) <- cells_in_order
  detection_mask <- expr_count_proxy > 0
  detection_mask[!is.finite(expr_count_proxy)] <- FALSE

  rank_mask <- score_vec_single > 0
  rank_mask[!is.finite(score_vec_single)] <- FALSE

  positive_mask <- rank_mask | detection_mask

  patient_vec <- if ("Patient" %in% colnames(meta_ct)) {
    as.character(meta_ct[cells_in_order, "Patient", drop = TRUE])
  } else if ("orig.ident" %in% colnames(meta_ct)) {
    as.character(meta_ct[cells_in_order, "orig.ident", drop = TRUE])
  } else {
    stop("Neither 'Patient' nor 'orig.ident' is available in meta_ct.")
  }

