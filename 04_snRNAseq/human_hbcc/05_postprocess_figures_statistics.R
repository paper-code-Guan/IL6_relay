}

fit_glmmTMB_with_warnings <- function(expr){
  warning_messages <- character()
  fit <- tryCatch(
    withCallingHandlers(
      expr,
      warning = function(w) {
        warning_messages <<- c(warning_messages, conditionMessage(w))
        invokeRestart("muffleWarning")
      }
    ),
    error = function(e) e
  )
  warning_text <- paste(unique(warning_messages), collapse = " | ")
  error_text <- if (inherits(fit, "error")) conditionMessage(fit) else ""
  diagnostic_text <- paste(warning_text, error_text)
  diagnostic_flag <- grepl(
    "convergence|non-positive-definite|singular|false convergence|hessian|nan|failed|not positive definite",
    diagnostic_text, ignore.case = TRUE
  ) || nzchar(error_text)
  list(fit = fit, warning = warning_text, error = error_text, warning_flag = diagnostic_flag)
}

extract_glmmTMB_p <- function(fit, term_regex){
  if (inherits(fit, "error")) return(NA_real_)
  coef_tab <- tryCatch(as.data.frame(summary(fit)$coefficients$cond), error = function(e) NULL)
  if (is.null(coef_tab) || !nrow(coef_tab)) return(NA_real_)
  p_col <- grep("^Pr\\(", colnames(coef_tab), value = TRUE)[1]
  if (is.na(p_col)) return(NA_real_)
  term <- grep(term_regex, rownames(coef_tab), value = TRUE)[1]
  if (is.na(term)) return(NA_real_)
  as.numeric(coef_tab[term, p_col])
}

extract_glmmTMB_effect <- function(fit, term_regex, ci_level = 0.95){
  na_out <- list(estimate = NA_real_, se = NA_real_,
                 ci_low = NA_real_, ci_high = NA_real_,
                 p_value = NA_real_, term = NA_character_)
  if (inherits(fit, "error") || is.null(fit)) return(na_out)
  coef_tab <- tryCatch(as.data.frame(summary(fit)$coefficients$cond), error = function(e) NULL)
  if (is.null(coef_tab) || !nrow(coef_tab)) return(na_out)
  p_col <- grep("^Pr\\(", colnames(coef_tab), value = TRUE)[1]
  if (!all(c("Estimate", "Std. Error", p_col) %in% colnames(coef_tab))) return(na_out)
  term <- grep(term_regex, rownames(coef_tab), value = TRUE)[1]
  if (is.na(term)) return(na_out)
  est <- as.numeric(coef_tab[term, "Estimate"])
  se <- as.numeric(coef_tab[term, "Std. Error"])
  z <- qnorm(1 - (1 - ci_level) / 2)
  list(
    estimate = est, se = se,
    ci_low = est - z * se, ci_high = est + z * se,
    p_value = as.numeric(coef_tab[term, p_col]),
    term = term
  )
}

compute_fold_change_HA <- function(per_donor,
                                   ctrl_level = "CTR",
                                   case_level = "SCZ",
                                   pseudocount = 0.5){
  agg <- per_donor %>%
    group_by(Group) %>%
    summarise(
      n_pos_pool = sum(n_positive, na.rm = TRUE),
      n_total_pool = sum(n_total, na.rm = TRUE),
      .groups = "drop"
    ) %>%
    mutate(rate_HA = (n_pos_pool + pseudocount) / (n_total_pool + 2 * pseudocount))
  ctrl_rate <- agg$rate_HA[agg$Group == ctrl_level]
  case_rate <- agg$rate_HA[agg$Group == case_level]
  list(
    ctrl_rate_HA = ctrl_rate, case_rate_HA = case_rate,
    fold_change = if (length(ctrl_rate) && length(case_rate)) case_rate / ctrl_rate else NA_real_,
    log2_fc = if (length(ctrl_rate) && length(case_rate)) log2(case_rate / ctrl_rate) else NA_real_,
    pseudocount_method = sprintf("Haldane-Anscombe-%.2f", pseudocount)
  )
}

