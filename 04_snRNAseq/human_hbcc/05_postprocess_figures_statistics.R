# ---------------------------------------------------------
# 17b) Per-figure source-data + statistics manifest (TXT)
#
#      Lists every PDF under figures/ alongside the CSV that holds the
#      Prism-rebuildable raw data, the statistical method, and the CSV
#      that holds the test statistic + P value. Maintained automatically
#      from filename patterns so adding a new cell type (e.g. Oligo)
#      requires no manual edit here.
# ---------------------------------------------------------
build_figure_data_stat_manifest <- function() {
  rel_path <- function(p) {
    if (length(p) == 0 || is.na(p) || !nzchar(p)) return(NA_character_)
    tryCatch(sub(paste0("^", normalizePath(out_root, winslash = "/", mustWork = FALSE), "/?"), "",
                 normalizePath(p, winslash = "/", mustWork = FALSE)),
             error = function(e) p)
  }
  pick_one <- function(dir, pat) {
    ff <- list.files(dir, pattern = pat, full.names = TRUE, recursive = TRUE)
    if (!length(ff)) return(NA_character_)
    ff[order(file.info(ff)$mtime, decreasing = TRUE)][1]
  }
  pdfs <- list.files(fig_dir, pattern = "\\.pdf$", full.names = TRUE)
  pdfs <- pdfs[order(basename(pdfs))]

  classify_one_pdf <- function(pdf_full) {
    pdf_name <- basename(pdf_full)
    src <- NA_character_; stats_file <- NA_character_
    method <- "Descriptive only (no inferential test for this figure)"
    aux  <- character(0)

    # Per-CT IL6 positive_proportion plots (per-donor boxplots; the prior
    # continuous-AUC IL6 score plots are removed in this release).
    m <- regmatches(pdf_name, regexec("^hbcc_([A-Za-z0-9]+)_IL6_positive_proportion_(with|no)_stats_", pdf_name))[[1]]
    if (length(m) == 3) {
      ct <- m[2]
      src <- pick_one(source_tab_dir, sprintf("^hbcc_%s_IL6_positive_proportion_source_data_.*\\.csv$", ct))
      stats_file <- pick_one(stat_tab_dir, "^proportion_pvalues_BH_adjusted_.*\\.csv$")
      method <- "IL6+ proportion two-group: GLMM-binomial (1|Patient) primary; BH-FDR across CT family"
      aux <- pick_one(stat_tab_dir, "^hbcc_il6_positive_GLMM_primary_.*\\.csv$")
      return(list(src=src, method=method, stats=stats_file, aux=aux))
    }
    # Ast GFAP+ proportion (the prior GFAP AUC score plot is removed)
    if (grepl("^hbcc_Ast_GFAP_positive_proportion_", pdf_name)) {
      src <- pick_one(source_tab_dir, "^hbcc_Ast_GFAP_positive_proportion_source_data_.*\\.csv$")
      stats_file <- pick_one(stat_tab_dir, "^proportion_pvalues_BH_adjusted_.*\\.csv$")
      method <- "GFAP+ proportion two-group: GLMM-binomial (1|Patient) primary"
      return(list(src=src, method=method, stats=stats_file, aux=aux))
    }
    # Mic AIF1+ proportion (the prior AIF1 AUC score plot is removed)
    if (grepl("^hbcc_Mic_AIF1_positive_proportion_", pdf_name)) {
      src <- pick_one(source_tab_dir, "^hbcc_Mic_AIF1_positive_proportion_source_data_.*\\.csv$")
      stats_file <- pick_one(stat_tab_dir, "^proportion_pvalues_BH_adjusted_.*\\.csv$")
      method <- "AIF1+ proportion two-group: GLMM-binomial (1|Patient) primary"
      return(list(src=src, method=method, stats=stats_file, aux=aux))
    }
    # IL6+ proportion heatmap (the prior standalone ExtNeu-vs-InbNeu
    # interaction figure is no longer generated; its source data and test
    # statistics are listed as aux files).
    if (grepl("^hbcc_il6_positive_proportion_heatmap_grouped_", pdf_name)) {
      src <- pick_one(source_tab_dir, "^hbcc_il6_positive_proportion_heatmap_source_data_.*\\.csv$")
      stats_file <- pick_one(stat_tab_dir, "^hbcc_il6_positive_GLMM_primary_.*\\.csv$")
      aux <- c(
        pick_one(source_tab_dir, "^hbcc_il6_positive_proportion_heatmap_interaction_source_data_.*\\.csv$"),
        pick_one(stat_tab_dir,   "^hbcc_il6_positive_interaction_Wilcoxon_primary_GLMM_sensitivity_.*\\.csv$")
      )
      method <- "Per-CT donor-level IL6+ mean rate shown as CTR/SCZ numeric tiles, plus log2FC = log2(SCZ/CTR) heatmap tile; interaction source/stat tables retained as aux files"
      return(list(src=src, method=method, stats=stats_file, aux=aux))
    }
    # Forest plot (single-gene IL6 only; the prior MSigDB module right panel is removed)
    if (grepl("^hbcc_IL6_forest_plot_", pdf_name)) {
      src <- pick_one(source_tab_dir, "^hbcc_IL6_forest_plot_source_data_.*\\.csv$")
      aux <- pick_one(fig_dir,        "^hbcc_IL6_forest_plot_caption_.*\\.txt$")
      stats_file <- pick_one(stat_tab_dir, "^proportion_pvalues_BH_adjusted_.*\\.csv$")
      method <- "Single-gene IL6 log OR with 95% CI (GLMM-binomial); two-sided P; BH-FDR within IL6+ proportion family (q reported in source data CSV only)"
      return(list(src=src, method=method, stats=stats_file, aux=aux))
    }
    # IL6+ donut (auto mainN)
    if (grepl("^hbcc_il6_positive_composition_main[0-9]+_donut_", pdf_name)) {
      n_match <- regmatches(pdf_name, regexec("main([0-9]+)_donut", pdf_name))[[1]]
      n <- if (length(n_match) >= 2) n_match[2] else "N"
      src <- pick_one(composition_tab_dir, sprintf("^hbcc_il6_positive_composition_main%s_.*\\.csv$", n))
      method <- "Descriptive composition: each cell type's IL6+ cell count as % of summed IL6+ cells across the main cell-type set; per-CT IL6+ counts shown in the donut legend"
      return(list(src=src, method=method, stats=stats_file, aux=aux))
    }
    # Cell type composition donut (counts merged into legend; the prior
    # separate hbcc_celltype_counts_barplot_*.pdf is no longer generated).
    if (grepl("^hbcc_celltype_composition_donut_", pdf_name)) {
      src <- pick_one(composition_tab_dir, "^hbcc_celltype_composition_.*\\.csv$")
      method <- "Descriptive cell-type composition (% of all cells); per-CT counts shown in the donut legend (no separate barplot)."
      return(list(src=src, method=method, stats=stats_file, aux=aux))
    }
    # UMAPs
    if (grepl("^hbcc_celltype_umap_", pdf_name)) {
      src <- pick_one(source_tab_dir, "^hbcc_celltype_umap_source_data_.*\\.csv$")
      method <- "Descriptive UMAP embedding coloured by cell type (no test)."
      return(list(src=src, method=method, stats=stats_file, aux=aux))
    }
    if (grepl("^hbcc_il6_positive_umap_", pdf_name)) {
      src <- pick_one(source_tab_dir, "^hbcc_il6_positive_umap_source_data_.*\\.csv$")
      stem <- sub("_[0-9]+\\.pdf$", "", pdf_name)
      aux <- pick_one(source_tab_dir, sprintf("^%s_positive_cells_.*\\.csv$", stem))
      method <- "Descriptive UMAP highlighting AUCell IL6+ cells (red) vs the rest (grey). Same dot diameter for both. No test."
      return(list(src=src, method=method, stats=stats_file, aux=aux))
    }
    if (grepl("^hbcc_il6_count_positive_umap_", pdf_name)) {
      src <- pick_one(source_tab_dir, "^hbcc_il6_count_positive_umap_source_data_.*\\.csv$")
      method <- "Descriptive UMAP highlighting cells with raw IL6 count > 0. No test."
      return(list(src=src, method=method, stats=stats_file, aux=aux))
    }
    # Marker dotplot (HBCC lightweight obj normally skips this)
    if (grepl("^hbcc_marker_dotplot_", pdf_name)) {
      src <- pick_one(source_tab_dir, "^hbcc_marker_dotplot_source_data_.*\\.csv$")
      method <- "Descriptive Seurat DotPlot of canonical markers (% expressed + scaled mean expression). No test."
      return(list(src=src, method=method, stats=stats_file, aux=aux))
    }
    list(src=NA_character_, method="Descriptive (no per-figure source CSV registered).",
         stats=NA_character_, aux=character(0))
  }

  blocks <- character(0)
  for (pdf in pdfs) {
    info <- classify_one_pdf(pdf)
    block <- c(
      sprintf("[FIGURE_FILE]   %s", basename(pdf)),
      sprintf("  source_data : %s", if (is.na(info$src) || !nzchar(info$src)) "N/A" else rel_path(info$src)),
      sprintf("  stat_method : %s", info$method),
      sprintf("  stat_values : %s", if (is.na(info$stats) || !nzchar(info$stats)) "N/A (descriptive figure)" else rel_path(info$stats))
    )
    if (length(info$aux) > 0 && any(!is.na(info$aux) & nzchar(info$aux))) {
      aux_clean <- info$aux[!is.na(info$aux) & nzchar(info$aux)]
      block <- c(block, sprintf("  aux_files   : %s", paste(vapply(aux_clean, rel_path, ""), collapse = " | ")))
    }
    block <- c(block, "  ----")
    blocks <- c(blocks, block)
  }

  header <- c(
    "============================================================",
    "HBCC STEP5 - FIGURE -> SOURCE DATA & STATISTICS MANIFEST",
    sprintf("Generated: %s", format(Sys.time(), "%Y-%m-%d %H:%M:%S %Z")),
    sprintf("Timestamp tag: %s", timestamp_tag),
    sprintf("Output root  : %s", normalizePath(out_root, winslash = "/", mustWork = FALSE)),
    "Paths below are relative to the output root.",
    "============================================================",
    ""
  )

  # ---- HBCC donor inclusion filter audit block ----
  filter_block <- c(
    "------------------------------------------------------------",
    "DONOR INCLUSION FILTER AUDIT",
    "------------------------------------------------------------"
  )
  if (isTRUE(hbcc_donor_filter_active)) {
    filter_block <- c(filter_block,
      sprintf("Status            : ACTIVE"),
      sprintf("Metadata source   : %s", hbcc_donor_filter_summary$metadata_path),
      sprintf("Age cutoff (CTR)  : >= %g years", hbcc_min_age_years),
      sprintf("Comorbid exclusion: %s  (any of AD/DLBD/FTD/Tauopathy/Vascular/ASCVD/Bipolar/Parkinson/TD == 'Yes')",
              if (hbcc_exclude_comorbid) "ENABLED" else "DISABLED"),
      sprintf("Per-CT n_cells    : >= %d cells per donor per cell type (Squair 2021 PMID 34584091)",
              hbcc_min_cells_per_ct),
      "",
      "Cohort after age + comorbid filter:",
      sprintf("  CTR n = %d   SCZ n = %d   total = %d",
              hbcc_balance_summary$n_ctr, hbcc_balance_summary$n_scz,
              hbcc_balance_summary$n_ctr + hbcc_balance_summary$n_scz),
      sprintf("  Sex     : CTR %.0f%% male vs SCZ %.0f%% male  (chi-square P = %.3g)",
              hbcc_balance_summary$ctr_male_pct, hbcc_balance_summary$scz_male_pct,
              hbcc_balance_summary$sex_chisq_p),
      sprintf("  Ancestry: CTR %.0f%% African vs SCZ %.0f%% African  (Fisher Monte-Carlo P = %.3g)",
              hbcc_balance_summary$ctr_african_pct, hbcc_balance_summary$scz_african_pct,
              hbcc_balance_summary$ancestry_fisher_p),
      sprintf("  Age (CTR): median = %.1f yr, range = [%.1f, %.1f]",
              hbcc_balance_summary$ctr_age_median,
              hbcc_balance_summary$ctr_age_range[1], hbcc_balance_summary$ctr_age_range[2]),
      sprintf("  Age (SCZ): median = %.1f yr, range = [%.1f, %.1f]",
              hbcc_balance_summary$scz_age_median,
              hbcc_balance_summary$scz_age_range[1], hbcc_balance_summary$scz_age_range[2]),
      "",
      sprintf("Excluded CTR donors by age<%g (n=%d):", hbcc_min_age_years, length(hbcc_excluded_age)),
      if (length(hbcc_excluded_age)) paste0("  ", paste(hbcc_excluded_age, collapse = ", ")) else "  (none)",
      sprintf("Excluded CTR donors by comorbidity (n=%d):", length(hbcc_excluded_comorbid)),
      if (length(hbcc_excluded_comorbid)) paste0("  ", paste(hbcc_excluded_comorbid, collapse = ", ")) else "  (none)",
      "",
      "Per-(CT,feature) donors dropped by n_cells<threshold:"
    )
    .keys <- ls(hbcc_drop_n_cells_log, sorted = TRUE)
    if (length(.keys)) {
      for (.k in .keys) {
