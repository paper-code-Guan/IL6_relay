mixed_score_group_test <- function(data, y_var, group_levels = display_levels){
  df <- data %>%
    mutate(Group = factor(normalize_group(Group), levels = group_levels),
           Patient = as.factor(Patient),
           .y = as.numeric(.data[[y_var]])) %>%
    filter(Group %in% group_levels, is.finite(.y), !is.na(Patient))

  if (nrow(df) < 2 || length(unique(df$Group)) < 2 || length(unique(df$Patient)) < 2) {
    return(data.frame(
      primary_method = "glmmTMB_gaussian_random_patient",
      primary_p = NA_real_, effect_metric = "mean_diff_score",
      effect_estimate = NA_real_, effect_se = NA_real_,
      effect_ci_low = NA_real_, effect_ci_high = NA_real_,
      primary_warning = "insufficient groups or patients",
      primary_error = "", primary_warning_flag = TRUE,
      n_cells = nrow(df), n_patients = length(unique(df$Patient)),
      stringsAsFactors = FALSE))
  }
  fit_res <- fit_glmmTMB_with_warnings(
    glmmTMB::glmmTMB(.y ~ Group + (1 | Patient), data = df, family = gaussian()))
  eff <- extract_glmmTMB_effect(fit_res$fit, "^Group")
  data.frame(
    primary_method = "glmmTMB_gaussian_random_patient",
    primary_p = eff$p_value, effect_metric = "mean_diff_score",
    effect_estimate = eff$estimate, effect_se = eff$se,
    effect_ci_low = eff$ci_low, effect_ci_high = eff$ci_high,
    primary_warning = fit_res$warning, primary_error = fit_res$error,
    primary_warning_flag = fit_res$warning_flag,
    n_cells = nrow(df), n_patients = length(unique(df$Patient)),
    stringsAsFactors = FALSE)
}

