# =========================================================
# HBCC step5: post-processing & final plotting (AUCell-based)
#
# Cohort:
#   HBCC schizophrenia case-control snRNA-seq from human dorsolateral
#   prefrontal cortex (DLPFC). Full whole-tissue (NOT NeuN+ sorted)
#   raw cohort: 146 Normal + 50 SCZ donors, 5 main cell types
#   (Ast / ExcitNeu / InhibNeu / Mic / OL).
#
# Donor inclusion filters (paper methods compliance, env-var gated):
#   * HBCC_METADATA_PATH        : path to per-cell metadata CSV. When set,
#                                  enables the three filters below.
#   * HBCC_MIN_AGE_YEARS  (=21) : CTR-only, age range matched to cases.
#   * HBCC_EXCLUDE_COMORBID(=T) : drop CTR with documented neuropsychiatric
#                                  / neurodegenerative comorbidity.
#   * HBCC_MIN_CELLS_PER_CT(=50): per-(CT, feature), drop donors with
#                                  fewer than N cells (Squair 2021 PMID
#                                  34584091).
#
# Expected input:
#   1) Lightweight Seurat object built by 00_build_lightweight_object.R
#      (5 per-CT RDS merged, KEEP_GENES = AIF1+GFAP by default; global
#      umap_35 reduction attached). Path:
#        export SEURAT_RDS_PATH=/path/to/hbcc_lightweight.rds
#   2) Formal AUCell output directory generated by 04_aucell_scoring.R
#      (one run per CT RDS, all writing into the same hbcc_IL6_<timestamp>
#      directory). Prefer forcing via:
#        export HBCC_RESULT_ROOT=/path/to/hbcc_IL6_YYYYMMDDHHMM
#      If HBCC_RESULT_ROOT is unset, the newest hbcc_IL6_<timestamp>
#      directory under HBCC_BASE_PATH/results will be auto-detected.
#   3) (Optional) HBCC per-cell metadata CSV with donor_id, group,
#      development_stage, sex, genetic_ancestry, and disease-status
#      columns (AD/DLBD/FTD/Tauopathy/Vascular/ASCVD/Bipolar/Parkinson/TD).
#
# Figure outputs (default ON; light-mode skips Fig1d/Fig4c only):
#   1)  Celltype UMAP by class                              (Fig1a)
#   2)  Cell-class counts barplot                            (Fig1b)
#   3)  Cell-class composition donut                         (Fig1c)
#   4)  Marker DotPlot                                       (Fig1d, gated by gene availability)
#   5)  AUCell-positive IL6 UMAP, main CTs                   (Fig4a)
#   6)  AUCell-positive IL6 UMAP, all 5 CTs                  (Fig4b)
#   7)  IL6 raw-count positive UMAP                          (Fig4c, gated by IL6 in obj)
#   8)  AUCell IL6+ composition donut, main CTs              (Fig5)
#   9)  Per-CT IL6 / GFAP / AIF1 score plots                  (with_stats + no_stats)
#   10) Per-CT IL6 / GFAP / AIF1 positive-proportion plots   (with_stats + no_stats)
#   11) MSigDB Hallmark IL6/JAK/STAT3 module score plots     (per CT)
#   12) IL6+ proportion grouped heatmap (donor-mean)          (CTR / Pooled / SCZ; log10 colour)
#   13) Excitatory-vs-inhibitory IL6+ proportion interaction
#   14) IL6 forest plot (single-gene + module panels)
#
# Statistical methods (only two inferential families):
#   * GLMM (glmmTMB) with random per-donor intercept:
#       - score path     : gaussian, AUC ~ Group + (1|Patient)
#       - proportion path: binomial, positive ~ Group + (1|Patient)
#       - interaction    : positive ~ Group * Celltype_use + (1|Patient)
#   * Donor-level Wilcoxon rank-sum on per-donor summaries:
#       - sensitivity for score and proportion (donor-mean)
#       - PRIMARY for excitatory-vs-inhibitory interaction
#         (cell-level GLMM as sensitivity)
#   Multiplicity controlled via Benjamini-Hochberg FDR within each
#   cell-type family. Fold change estimated via Haldane-Anscombe
#   pseudocount.
#
# Notes:
#   - Single-gene cytokine positivity (IL6, GFAP, AIF1) follows the
#     rank-and-detection rule from step4: positive = (AUC > 0 at extended
#     top window aucMaxRank=0.10*G) OR (raw count > 0). Multi-gene module
#     positivity uses AUCell's selected threshold on the default top
#     window (aucMaxRank=0.05*G).
#   - Score and proportion plots are exported in two versions:
#       *_with_stats_*.pdf : Mean and GLMM P annotated
#       *_no_stats_*.pdf   : no annotation
#   - All five cell types (Ast / ExcitNeu / InhibNeu / Mic / OL) are
#     first-class endpoints in HBCC (whole-tissue cohort, no NeuN+
#     enrichment); the legacy "Others" CT used in the Batiuk pipeline
#     is intentionally excluded throughout.
# =========================================================

