plot_score_single_panel <- function(data,
                                   y_var = "score",
                                   title = NULL,
                                   y_label = "AUC score",
                                   group_levels = NULL,
                                   group_colors = NULL,
                                   axis_title_size = 23,
                                   axis_text_size = 23,
                                   font_family_main = plot_font_family,
                                   point_size = 2.0,
                                   point_alpha = 1.00,
                                   point_stroke = 0,
                                   jitter_w = 0.12,
                                   axis_line_pt = 0.8,
                                   stat_label_size_pt = 20,
                                   p_label_size_pt = 21,
                                   show_stats = TRUE){
  # Input MUST be cell-level data with columns Group, Patient and y_var.
  # GLMM uses cell-level rows nested within Patient; donor-level aggregation
  # is used only for plotting donor summaries.
  if (is.null(group_levels)) group_levels <- display_levels
  if (is.null(group_colors)) group_colors <- get("group_colors", envir = parent.frame())
  if (!"Group" %in% colnames(data)) stop("Group column missing.")
  if (!y_var %in% colnames(data)) stop(paste0(y_var, " column missing."))
  group_colors <- group_colors[group_levels]
  data <- data %>%
    mutate(Group = factor(normalize_group(Group), levels = group_levels)) %>%
    filter(Group %in% group_levels)
  if (!nrow(data)) stop("No rows left after Group filtering.")
  if (!"Patient" %in% colnames(data)) stop("'Patient' column missing. Re-run step 4 so donor identities are written to the score tables.")

  mixed_test <- mixed_score_group_test(data, y_var, group_levels)
  data <- data %>%
    group_by(Patient, Group) %>%
    summarise(.plot_value = mean(.data[[y_var]], na.rm = TRUE), .groups = "drop") %>% ungroup()
  names(data)[names(data) == ".plot_value"] <- y_var
  stats_df <- data %>% group_by(Group) %>% summarise(mean_value = mean(.data[[y_var]], na.rm = TRUE), .groups = "drop")
  p_val_glmm <- mixed_test$primary_p[1]
  p_lab <- format_p_method(p_val_glmm, "GLMM")

  rng <- range(data[[y_var]], na.rm = TRUE)
  if (!all(is.finite(rng))) rng <- c(0, 1)
  d <- diff(rng)
  if (d == 0) d <- max(abs(rng[1]), 0.001)
  if (show_stats) {
    y_low <- rng[1] - 0.06 * d
    y_high <- rng[2] + 0.62 * d
    y_mean <- y_high - 0.06 * d
    y_p <- y_high - 0.18 * d
  } else {
    y_low <- rng[1] - 0.04 * d
    y_high <- rng[2] + 0.04 * d
  }

  p <- ggplot(data, aes(x = Group, y = .data[[y_var]], fill = Group, colour = Group)) +
    geom_point(
      position = position_jitter(width = jitter_w, height = 0),
      alpha = point_alpha,
      size = point_size,
      stroke = point_stroke,
      shape = 16
    ) +
    stat_summary(fun = mean, geom = "crossbar", width = 0.55, colour = "black", linewidth = 0.45) +
    scale_fill_manual(values = group_colors) +
    scale_colour_manual(values = group_colors) +
    scale_y_continuous(limits = c(y_low, y_high)) +
    labs(title = title, x = NULL, y = y_label) +
    theme_classic(base_size = axis_text_size, base_family = font_family_main) +
    theme(
      plot.title = element_text(size = axis_title_size, face = "bold", hjust = 0.5),
      axis.title.y = element_text(size = axis_title_size, face = "bold"),
      axis.text.x = element_text(size = min(axis_text_size, group_axis_text_size), face = "bold"),
      axis.text.y = element_text(size = axis_text_size, face = "bold"),
      axis.line = element_line(linewidth = axis_line_pt),
      legend.position = "none",
      plot.margin = margin(10, 10, 12, 10)
    ) +
    theme_axis_black()

  if (show_stats) {
    eff_estimate <- mixed_test$effect_estimate[1]
    eff_ci_low <- mixed_test$effect_ci_low[1]
    eff_ci_high <- mixed_test$effect_ci_high[1]
    if (!is.na(eff_estimate) && !is.na(eff_ci_low) && !is.na(eff_ci_high)) {
      eff_lab <- sprintf("dScore = %.4f (95%% CI %.4f-%.4f)", eff_estimate, eff_ci_low, eff_ci_high)
    } else {
      eff_lab <- "dScore = NA"
    }
    ctrl_mean <- stats_df$mean_value[stats_df$Group == group_levels[1]]
    case_mean <- stats_df$mean_value[stats_df$Group == group_levels[2]]
    arrow_lab <- if (length(case_mean) && length(ctrl_mean) && is.finite(case_mean) && is.finite(ctrl_mean)) {
      if (case_mean > ctrl_mean) "SCZ up" else if (case_mean < ctrl_mean) "SCZ down" else "no change"
    } else "NA"

    p <- p +
      geom_text(data = stats_df,
                aes(x = Group, y = y_mean, label = sprintf("Mean = %.4f", mean_value)),
                inherit.aes = FALSE, family = font_family_main, fontface = "bold",
                vjust = 0, size = stat_label_size_pt / 10, colour = "black") +
      annotate("text", x = (length(group_levels) + 1) / 2, y = y_p + 0.18 * d,
               label = paste0(eff_lab, "    ", arrow_lab),
               family = font_family_main, fontface = "bold",
               vjust = 0, size = (p_label_size_pt - 2) / 10, colour = "black") +
      annotate("text", x = (length(group_levels) + 1) / 2, y = y_p,
               label = p_lab,
               family = font_family_main, fontface = "italic",
               vjust = 0, size = p_label_size_pt / 10, colour = "black")
  }

  list(
    plot = p,
    p_value = p_val_glmm,
    stats = stats_df,
    test_stats = mixed_test
  )
}

format_prop_p <- function(p) {
  vapply(p, function(x) {
    if (is.na(x) || !is.finite(x)) return("NA")
    if (x < 0.001) return("<0.001")
    sprintf("%.4f", x)
  }, character(1))
}

plot_proportion_panel <- function(test_pair, ct_name, feature_name, y_label = NULL, show_stats = TRUE) {
  per_donor <- test_pair$per_donor
  if (is.null(y_label)) y_label <- sprintf("%s+ proportion", feature_name)
  group_colors_use <- group_colors[display_levels]
  stats_df <- per_donor %>% group_by(Group) %>% summarise(mean_value = mean(proportion, na.rm = TRUE), .groups = "drop")
  rng <- range(per_donor$proportion, na.rm = TRUE)
  if (!all(is.finite(rng))) rng <- c(0, 0.01)
  if (diff(rng) == 0) rng <- c(max(0, rng[1] - 0.005), rng[2] + 0.01)
  d <- max(diff(rng), 1e-3)
  if (show_stats) {
    y_low <- max(0, rng[1] - 0.06 * d)
    y_high <- rng[2] + 1.45 * d
    y_mean <- y_high - 0.10 * d
    y_or <- y_high - 0.34 * d
    y_fc <- y_high - 0.56 * d
    y_glmm <- y_high - 0.78 * d
  } else {
    y_low <- max(0, rng[1] - 0.04 * d)
    y_high <- rng[2] + 0.04 * d
  }

  title_str <- sprintf("%s (donors = %s, cells = %d)", pretty_ct_fig(ct_name), test_pair$n_donors_per_group, test_pair$n_total_cells)
  p <- ggplot(per_donor, aes(x = Group, y = proportion, fill = Group, colour = Group)) +
    geom_point(position = position_jitter(width = 0.12, height = 0), alpha = 1.0, size = 2.5, stroke = 0, shape = 16) +
    stat_summary(fun = mean, geom = "crossbar", width = 0.55, colour = "black", linewidth = 0.45) +
    scale_fill_manual(values = group_colors_use) +
    scale_colour_manual(values = group_colors_use) +
    scale_y_continuous(labels = function(x) sprintf("%.1f%%", x * 100), limits = c(y_low, y_high)) +
    labs(title = title_str, x = NULL, y = y_label) +
    theme_classic(base_size = 22, base_family = plot_font_family) +
    theme(
      plot.title = element_text(size = 14, face = "bold", hjust = 0.5),
      axis.title.y = element_text(size = 22, face = "bold"),
      axis.text.x = element_text(size = group_axis_text_size, face = "bold"),
      axis.text.y = element_text(size = 22, face = "bold"),
      axis.line = element_line(linewidth = 0.8),
      legend.position = "none",
      plot.margin = margin(10, 10, 12, 10)
    ) +
    theme_axis_black()

  if (show_stats) {
    eff_lab <- if (!is.na(test_pair$OR) && !is.na(test_pair$OR_ci_low) && !is.na(test_pair$OR_ci_high)) {
      sprintf("OR = %.2f (95%% CI %.2f-%.2f)", test_pair$OR, test_pair$OR_ci_low, test_pair$OR_ci_high)
    } else {
      "OR = NA"
    }
    case_mean <- mean(per_donor$proportion[per_donor$Group == display_levels[2]], na.rm = TRUE)
    ctrl_mean <- mean(per_donor$proportion[per_donor$Group == display_levels[1]], na.rm = TRUE)
    arrow_lab <- if (is.finite(case_mean) && is.finite(ctrl_mean)) {
      if (case_mean > ctrl_mean) "SCZ up" else if (case_mean < ctrl_mean) "SCZ down" else "no change"
    } else "NA"
    fc_lab <- if (!is.na(test_pair$fold_change_HA)) sprintf("FC = %.2fx (HA-corrected)", test_pair$fold_change_HA) else "FC = NA"
    glmm_lab <- sprintf("GLMM P = %s", format_prop_p(test_pair$glmm_p))
    p <- p +
      geom_text(data = stats_df,
                aes(x = Group, y = y_mean, label = sprintf("Mean = %.2f%%", mean_value * 100)),
                inherit.aes = FALSE, family = plot_font_family, fontface = "bold",
                vjust = 0, size = 4.8, colour = "black") +
      annotate("text", x = 1.5, y = y_or, label = paste0(eff_lab, "    ", arrow_lab),
               family = plot_font_family, fontface = "bold", size = 4.4, colour = "black", hjust = 0.5) +
      annotate("text", x = 1.5, y = y_fc, label = fc_lab,
               family = plot_font_family, fontface = "italic", size = 4.2, colour = "black", hjust = 0.5) +
      annotate("text", x = 1.5, y = y_glmm, label = glmm_lab,
               family = plot_font_family, fontface = "italic", size = 4.2, colour = "black", hjust = 0.5)
  }
  p
}

plot_score_and_save <- function(df, out_pdf, title = NULL, y_label = "AUC score", show_stats = TRUE) {
  pp <- plot_score_single_panel(
    data = df, y_var = "score", title = title, y_label = y_label,
    axis_title_size = 23, axis_text_size = 23, show_stats = show_stats
  )
  save_plot_pdf(pp$plot, out_pdf, width = 10, height = 8.8, units = "cm")
  if (isTRUE(show_stats) && !is.null(pp$test_stats)) {
    score_mixed_test_tables[[length(score_mixed_test_tables) + 1L]] <<- data.frame(
      plot_file = basename(out_pdf),
      Celltype_use = paste(unique(df$Celltype_use), collapse = ";"),
      feature_set = paste(unique(df$feature_set), collapse = ";"),
      pp$test_stats,
      stringsAsFactors = FALSE
    )
    ts <- pp$test_stats
    ct_str <- paste(unique(df$Celltype_use), collapse = ";")
    ft_str <- paste(unique(df$feature_set), collapse = ";")
    prior_d <- get_prior_direction(ct_str, ft_str)
    obs_d <- sign(ts$effect_estimate[1])
    register_main_p(
      plot_file = basename(out_pdf),
      celltype = ct_str,
      feature_set = ft_str,
      p_value = pp$p_value,
      test_method = "cell-level GLMM with donor random intercept",
      effect_metric = ts$effect_metric[1],
      effect_estimate = ts$effect_estimate[1],
      effect_se = ts$effect_se[1],
      effect_ci_low = ts$effect_ci_low[1],
      effect_ci_high = ts$effect_ci_high[1],
      prior_direction = prior_d,
      observed_direction = obs_d,
      direction_match = !is.na(prior_d) && !is.na(obs_d) && (prior_d == 0 || sign(prior_d) == sign(obs_d))
    )
  }
  invisible(pp)
}

