format_pq_label <- function(x, prefix) {
  vapply(x, function(v) {
    if (is.na(v) || !is.finite(v)) return(paste0(prefix, "=NA"))
    if (v < 0.001) return(paste0(prefix, "<0.001"))
    sprintf("%s=%.3f", prefix, v)
  }, character(1))
}

plot_forest_panel <- function(forest_data, out_pdf){
  forest_label_map <- c("ExcitNeu" = "ExtNeu", "InhibNeu" = "InbNeu",
                       "Ast" = "Astro", "Mic" = "MiGlia", "OL" = "Oligo")
  base_order <- c("ExcitNeu", "InhibNeu", "Ast")
  if ("Mic" %in% cts_main) base_order <- c(base_order, "Mic")
  if ("OL"  %in% cts_main) base_order <- c(base_order, "OL")
  yl_levels <- rev(base_order)
  sg <- forest_data %>% mutate(
    cell_type = factor(cell_type, levels = yl_levels),
    cell_type_label = factor(forest_label_map[as.character(cell_type)],
                             levels = forest_label_map[yl_levels])
  )

  axis_low   <- -1.5
  axis_high  <-  1.5
  text_right <-  3.3
  tick_breaks <- c(-1.5, -1, 0, 1, 1.5)
  tick_labels <- c("-1.5", "-1", "0", "1", "1.5")

  # Row label shows P and BH-adjusted q with 3-decimal precision (<0.001
  # rendered as "<0.001"). The diamond x-position remains the log OR point
  # estimate, matching the x-axis "log OR (95% CI)" scale.
  sg <- sg %>% mutate(
    estimate_plot = pmax(pmin(estimate, axis_high), axis_low),
    ci_low_plot   = pmax(ci_low,  axis_low),
    ci_high_plot  = pmin(ci_high, axis_high),
    row_label_text = sprintf("%s, %s",
                             format_pq_label(p_value, "P"),
                             format_pq_label(q_BH,   "q"))
  )

  n_rows <- nrow(sg)
  # Custom axis layout. The data rows occupy y in [1, n_rows] (factor positions
  # bottom-to-top). The x-axis line sits just below row 1 at y = axis_y; the
  # y-axis line stands at x = axis_low and extends from y = axis_y (bottom)
  # up to y = n_rows + 0.30 (leaving headroom above the topmost row), so the
  # two axis lines meet at right angle at the corner (axis_low, axis_y) and
  # the y-axis does not protrude excessively. Both axis lines (and the
  # y-axis ticks and x-axis ticks) share the same line width via
  # axis_linewidth so the rendered axes look visually balanced.
  axis_y         <- 0.4
  y_axis_top     <- n_rows + 0.30
  tick_y_bot     <- 0.30   # x-axis tick mark inner end (below axis_y)
  tick_lab_y     <- 0.20   # x-axis tick labels (top of label text)
  title_y        <- -0.10  # x-axis title (top of text)
  y_tick_left    <- axis_low - (axis_high - axis_low) * 0.020  # y-axis tick mark inner end
  axis_linewidth <- 0.5

  p <- ggplot(sg, aes(x = estimate_plot, y = cell_type_label)) +
    geom_errorbar(aes(xmin = ci_low_plot, xmax = ci_high_plot),
                  width = 0.2, colour = "black", linewidth = 0.8, orientation = "y") +
    geom_point(colour = "#F47F72", size = 4, shape = 18) +
    geom_text(aes(label = row_label_text),
              x = axis_high + 0.10, hjust = 0,
              size = 3.6, family = plot_font_family, colour = "black") +
    # Reference dashed line at x = 0, restricted to the y-axis range
    # [axis_y, y_axis_top]. Placed after the discrete-y data geoms so the
    # y-scale is already established as discrete by geom_errorbar before
    # annotate's numeric y values are processed.
    annotate("segment",
             x = 0, xend = 0,
             y = axis_y, yend = y_axis_top,
             linetype = "dashed", colour = "grey60") +
    # X axis line + ticks + labels (linewidth = axis_linewidth).
    annotate("segment",
             x = axis_low, xend = axis_high,
             y = axis_y, yend = axis_y,
             colour = "black", linewidth = axis_linewidth) +
    annotate("segment",
             x = tick_breaks, xend = tick_breaks,
             y = axis_y, yend = tick_y_bot,
             colour = "black", linewidth = axis_linewidth) +
    annotate("text",
             x = tick_breaks, y = tick_lab_y,
             label = tick_labels,
             hjust = 0.5, vjust = 1,
             size = 3.6, family = plot_font_family, colour = "black") +
    annotate("text",
             x = (axis_low + axis_high) / 2, y = title_y,
             label = "log OR (95% CI)",
             hjust = 0.5, vjust = 1,
             size = 4.2, fontface = "bold",
             family = plot_font_family, colour = "black") +
    # Y axis line + per-row ticks (linewidth = axis_linewidth). Y axis bottom
    # anchors to the x-axis line at the corner (axis_low, axis_y), forming a
    # right-angle intersection; y axis top stops at n_rows + 0.10 so the line
    # does not extend significantly past the topmost data row.
    annotate("segment",
             x = axis_low, xend = axis_low,
             y = axis_y, yend = y_axis_top,
             colour = "black", linewidth = axis_linewidth) +
    annotate("segment",
             x = y_tick_left, xend = axis_low,
             y = seq_len(n_rows), yend = seq_len(n_rows),
             colour = "black", linewidth = axis_linewidth) +
    scale_x_continuous(breaks = tick_breaks) +
    coord_cartesian(xlim = c(axis_low, text_right), clip = "off") +
    labs(title = NULL, x = NULL, y = NULL) +
    theme_classic(base_size = 14, base_family = plot_font_family) +
    theme(
      axis.title.x = element_blank(),
      axis.text.x  = element_blank(),
      axis.line.x  = element_blank(),
      axis.ticks.x = element_blank(),
      axis.text.y  = element_text(face = "bold", colour = "black"),
      axis.line.y  = element_blank(),
      axis.ticks.y = element_blank(),
      panel.background = element_blank(),
      plot.margin = margin(10, 6, 22, 6)
    )

  save_plot_pdf(p, out_pdf, width = 11, height = 10, units = "cm")
}
