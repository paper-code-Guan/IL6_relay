# ---------------------------------------------------------------------------
# Light mode (HBCC 5-CT lightweight obj workflow).
#
# In the HBCC 5-CT workflow the lightweight obj only carries 2-3
# specifically requested genes (e.g. AIF1, GFAP, optionally IL6). Two
# figure blocks REQUIRE genes that are not in the lightweight matrix
# and are therefore guarded by per-block gene-availability checks:
#   (d) Fig1d canonical marker DotPlot       -> needs many CT markers
#   (e) Fig4c IL6 raw-count positive UMAP   -> needs IL6 raw counts
# Both blocks gracefully skip with a message when the required genes
# are not available; HBCC_STEP5_LIGHT_MODE=TRUE additionally forces a
# skip even if the genes are present (useful when the user does not
# want those legacy figures regenerated).
#
