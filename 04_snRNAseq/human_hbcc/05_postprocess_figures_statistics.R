format_p <- function(p) {
  if (is.na(p) || !is.finite(p)) return("P = NA")
  if (p == 0) return("P < 2.2e-16")
  if (p < 0.01) return(paste0("P = ", format(p, scientific = TRUE, digits = 2)))
  sprintf("P = %.4f", p)
}

