# ---------------------------------------------------------------------------
# HBCC donor inclusion filters (paper methods compliance).
#
# Three pre-specified, a-priori filters applied to the CTR group only:
#   (i)   age range matching: CTR donor age >= HBCC_MIN_AGE_YEARS (default 21)
#   (ii)  comorbidity exclusion: drop CTR donors with documented neuro-
#         psychiatric comorbidity (AD/DLBD/FTD/Tauopathy/Vascular/ASCVD/
#         Bipolar/Parkinson/Tardive_dyskinesia == "Yes" in metadata CSV).
#         Toggled by HBCC_EXCLUDE_COMORBID (default TRUE).
#   (iii) per-CT minimum cell count: drop donor (any group) from a given
#         cell-type's analysis when that donor contributes fewer than
#         HBCC_MIN_CELLS_PER_CT cells in that cell type (default 50,
#         single-cell QC standard; Squair et al., 2021, Nat Commun PMID
#         34584091). Applied INSIDE read_score_table per (ct, feature).
#
# All filters are bypassed when HBCC_METADATA_PATH is unset / unreadable.
# ---------------------------------------------------------------------------
