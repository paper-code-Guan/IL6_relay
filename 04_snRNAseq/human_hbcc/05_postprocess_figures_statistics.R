      summarise(expected_n_genes = dplyr::first(na.omit(expected_n_genes)),
                found_n_genes = dplyr::first(na.omit(found_n_genes)),
                fraction_recovered = dplyr::first(na.omit(fraction_recovered)),
                missing_genes = dplyr::first(na.omit(missing_genes)),
                .groups = "drop")
  } else {
    tibble::tibble(Celltype_use=character(), feature_set=character(), expected_n_genes=numeric(), found_n_genes=numeric(), fraction_recovered=numeric(), missing_genes=character())
  }

  s1 <- bind_rows(lapply(cts_main, function(ct) {
    read_score_table(ct, "IL6", keep_cols = c("Group", "Patient", "score")) %>%
      group_by(Patient, Group, Celltype_use) %>%
      summarise(mean_AUC_score = mean(score, na.rm = TRUE), n_total_cells = dplyr::n(), .groups = "drop")
  }))
  openxlsx::addWorksheet(wb, "IL6_score_per_donor")
  openxlsx::writeData(wb, "IL6_score_per_donor", s1)

  s2 <- bind_rows(lapply(proportion_pair_results[paste0(cts_main, "__IL6")], function(pr) if (!is.null(pr)) pr$per_donor else NULL))
  openxlsx::addWorksheet(wb, "IL6_proportion_per_donor")
  openxlsx::writeData(wb, "IL6_proportion_per_donor", s2)

  s3 <- if (length(cts_module)) bind_rows(lapply(cts_module, function(ct) {
    read_score_table(ct, msigdb_il6_jak_stat3_feature, keep_cols = c("Group", "Patient", "score")) %>%
      group_by(Patient, Group, Celltype_use) %>%
      summarise(mean_AUC_score = mean(score, na.rm = TRUE), n_total_cells = dplyr::n(), .groups = "drop")
  })) else data.frame(Patient = character(), Group = character(), Celltype_use = character(),
                       mean_AUC_score = numeric(), n_total_cells = integer())
  openxlsx::addWorksheet(wb, "IL6_JAK_STAT3_score_donor")
  openxlsx::writeData(wb, "IL6_JAK_STAT3_score_donor", s3)

  s4_score <- if (!is.null(df_ast_gfap)) df_ast_gfap %>% group_by(Patient, Group, Celltype_use) %>% summarise(mean_AUC_score = mean(score, na.rm = TRUE), .groups = "drop") else data.frame()
  s4 <- if (!is.null(proportion_pair_results[["Ast__GFAP"]])) proportion_pair_results[["Ast__GFAP"]]$per_donor %>% left_join(s4_score, by = c("Patient", "Group", "Celltype_use")) else data.frame(note = "GFAP not available")
  openxlsx::addWorksheet(wb, "GFAP_per_donor")
  openxlsx::writeData(wb, "GFAP_per_donor", s4)

  if (mic_avail$has_mic && !is.null(proportion_pair_results[["Mic__AIF1"]])) {
    s5_score <- aif1_mic_df %>% group_by(Patient, Group, Celltype_use) %>% summarise(mean_AUC_score = mean(score, na.rm = TRUE), .groups = "drop")
    s5 <- proportion_pair_results[["Mic__AIF1"]]$per_donor %>% left_join(s5_score, by = c("Patient", "Group", "Celltype_use"))
  } else {
    s5 <- data.frame(
      Patient = character(),
      Group = factor(character(), levels = display_levels),
      n_total = integer(),
