export_main_p_registry <- function() {
  if (!length(main_p_registry)) return(invisible(NULL))
  ptab <- dplyr::bind_rows(main_p_registry) %>%
    mutate(q_BH = p.adjust(p_value, method = "BH"))
  write.csv(ptab, file.path(stat_tab_dir, sprintf("main_pvalues_BH_adjusted_%s.csv", timestamp_tag)), row.names = FALSE)
  invisible(ptab)
}

