      found_n_genes = dplyr::coalesce(found_n_genes, ifelse(feature_set %in% c("IL6","GFAP","AIF1"), 1, NA_real_)),
      fraction_recovered = dplyr::coalesce(fraction_recovered, ifelse(feature_set %in% c("IL6","GFAP","AIF1"), 1, NA_real_)),
      missing_genes = dplyr::coalesce(missing_genes, ifelse(feature_set %in% c("IL6","GFAP","AIF1"), "", NA_character_))
