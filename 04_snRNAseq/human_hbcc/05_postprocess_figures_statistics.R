      ifelse(
        grepl("month-old", .donor_md$development_stage),
        suppressWarnings(as.numeric(gsub("([0-9]+).*", "\\1", .donor_md$development_stage))) / 12,
        NA_real_
      )
    )
    .dz_cols <- c(
      "AD_status", "DLBD_status", "FTD_status", "Tauopathy_status",
      "Vascular_status", "ASCVD_status", "Bipolar_Disorder",
      "Parkinson_disease", "Tardive_dyskinesia"
    )
    .has_comorbid <- rep(FALSE, nrow(.donor_md))
    for (.cc in .dz_cols) {
      if (.cc %in% colnames(.donor_md)) {
        .has_comorbid <- .has_comorbid | (.donor_md[[.cc]] == "Yes")
      }
    }
  }

  .grp_norm <- normalize_group(.donor_md$group)
  .is_ctr <- .grp_norm == "CTR"
  .is_scz <- .grp_norm == "SCZ"

  if (.release_manifest) {
    .included <- .as_logical(.donor_md$included_after_donor_filter)
    .age_eligible <- if ("age_eligible" %in% colnames(.donor_md)) {
      .as_logical(.donor_md$age_eligible)
    } else {
      !is.na(.age_y) & .age_y >= hbcc_min_age_years
    }
    .excl_age <- .is_ctr & !.age_eligible
    .excl_comorbid <- .is_ctr & .has_comorbid
  } else {
    .excl_age <- .is_ctr & (is.na(.age_y) | .age_y < hbcc_min_age_years)
    .excl_comorbid <- if (hbcc_exclude_comorbid) {
      .is_ctr & .has_comorbid
    } else {
      rep(FALSE, nrow(.donor_md))
    }
    .included <- (.is_ctr & !.excl_age & !.excl_comorbid) | .is_scz
  }

  hbcc_excluded_age      <- as.character(.donor_md$donor_id[.excl_age & !.excl_comorbid])
  hbcc_excluded_comorbid <- as.character(.donor_md$donor_id[.excl_comorbid])
  hbcc_keep_donors       <- as.character(.donor_md$donor_id[.included])

  # Demographic balance on the post-age+comorbid cohort
  .kept_md <- .donor_md[match(hbcc_keep_donors, .donor_md$donor_id), , drop = FALSE]
  .kept_grp <- normalize_group(.kept_md$group)
  .ctr_md <- .kept_md[.kept_grp == "CTR", , drop = FALSE]
  .scz_md <- .kept_md[.kept_grp == "SCZ", , drop = FALSE]
  .ctr_age <- .age_y[match(.ctr_md$donor_id, .donor_md$donor_id)]
  .scz_age <- .age_y[match(.scz_md$donor_id, .donor_md$donor_id)]

  .sex_tab <- table(.kept_grp, .kept_md$sex)
  .sex_p   <- tryCatch(suppressWarnings(chisq.test(.sex_tab)$p.value),
                       error = function(e) NA_real_)
  .anc_tab <- table(.kept_grp, .kept_md$genetic_ancestry)
  .anc_p   <- tryCatch(suppressWarnings(
    fisher.test(.anc_tab, simulate.p.value = TRUE, B = 1e5)$p.value),
                       error = function(e) NA_real_)

  hbcc_balance_summary <- list(
    n_ctr = nrow(.ctr_md), n_scz = nrow(.scz_md),
    ctr_male_pct  = 100 * mean(.ctr_md$sex == "male", na.rm = TRUE),
    scz_male_pct  = 100 * mean(.scz_md$sex == "male", na.rm = TRUE),
    sex_chisq_p   = .sex_p,
    ctr_african_pct = 100 * mean(.ctr_md$genetic_ancestry == "African", na.rm = TRUE),
    scz_african_pct = 100 * mean(.scz_md$genetic_ancestry == "African", na.rm = TRUE),
    ancestry_fisher_p = .anc_p,
    ctr_age_median = stats::median(.ctr_age, na.rm = TRUE),
    scz_age_median = stats::median(.scz_age, na.rm = TRUE),
    ctr_age_range  = range(.ctr_age, na.rm = TRUE),
    scz_age_range  = range(.scz_age, na.rm = TRUE)
  )

  message(sprintf(
    "[HBCC donor filter] excluded %d age<%g + %d comorbid CTR -> kept %d donors (CTR=%d, SCZ=%d).",
    length(hbcc_excluded_age), hbcc_min_age_years,
    length(hbcc_excluded_comorbid), length(hbcc_keep_donors),
    hbcc_balance_summary$n_ctr, hbcc_balance_summary$n_scz))
  message(sprintf(
    "  Sex balance:      CTR %.0f%% male vs SCZ %.0f%% male (chi-square P=%.3g)",
    hbcc_balance_summary$ctr_male_pct, hbcc_balance_summary$scz_male_pct, .sex_p))
  message(sprintf(
    "  Ancestry (Afr):   CTR %.0f%% vs SCZ %.0f%% (Fisher Monte-Carlo P=%.3g)",
    hbcc_balance_summary$ctr_african_pct, hbcc_balance_summary$scz_african_pct, .anc_p))

  # Subset obj to kept donors only
  .n_before <- ncol(obj)
  .keep_cells <- as.character(obj$Patient) %in% hbcc_keep_donors
  obj <- obj[, .keep_cells]
  message(sprintf("[HBCC donor filter] obj cells: %d -> %d (drop %d)",
                  .n_before, ncol(obj), .n_before - ncol(obj)))

  # Re-capture md from the filtered obj so downstream Celltypes_raw etc.
  # see consistent lengths
  md <- obj@meta.data

  rm(.donor_md, .raw_md, .age_y, .has_comorbid, .grp_norm, .is_ctr, .is_scz,
     .excl_age, .excl_comorbid, .keep_cells, .n_before, .dz_cols,
     .kept_md, .kept_grp, .ctr_md, .scz_md, .ctr_age, .scz_age,
     .sex_tab, .sex_p, .anc_tab, .anc_p)
}

