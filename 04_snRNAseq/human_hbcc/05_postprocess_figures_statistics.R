make_positive_umap <- function(plot_df, positive_filter_cts, out_name,
                               point_size = 0.45,
                               group_filter = NULL,
                               write_positive_cells = TRUE) {
  # Default point_size matches the grey background dots so red IL6+ cells
  # have the same diameter as non-positive cells.
  if (!is.null(group_filter)) {
    plot_df <- plot_df %>% filter(Group %in% group_filter)
  }
  if (!nrow(plot_df)) {
    stop(sprintf("No cells available for %s after applying group filter.", out_name))
  }

  plot_df <- plot_df %>% mutate(red_positive = AUCell_IL6_positive %in% TRUE & Celltype_use %in% positive_filter_cts)

  label_df <- plot_df %>%
    filter(!is.na(Celltype_use)) %>%
    group_by(Celltype_fig_label) %>%
    summarise(
      UMAP_1 = median(UMAP_1, na.rm = TRUE),
      UMAP_2 = median(UMAP_2, na.rm = TRUE),
      .groups = "drop"
    ) %>%
    filter(is.finite(UMAP_1), is.finite(UMAP_2), !is.na(Celltype_fig_label), nzchar(as.character(Celltype_fig_label)))

  p <- ggplot() +
    geom_point(data = plot_df, aes(UMAP_1, UMAP_2), color = "#D9D9D9", size = 0.45, alpha = 0.85, shape = 16, show.legend = FALSE) +
    geom_point(data = plot_df %>% filter(red_positive), aes(UMAP_1, UMAP_2), color = "#D7301F", size = point_size, alpha = 0.95, shape = 16, show.legend = FALSE) +
    geom_text_repel(data = label_df, aes(UMAP_1, UMAP_2, label = Celltype_fig_label), color = "black", size = 5,
                    segment.color = NA, box.padding = 0.5, point.padding = 0.2, show.legend = FALSE) +
    labs(x = "UMAP1", y = "UMAP2") +
    theme_classic(base_size = 12) +
    theme(
      panel.grid = element_blank(),
      panel.border = element_blank(),
      axis.text = element_blank(),
      axis.ticks = element_blank(),
      axis.title = element_text(size = 16),
      legend.position = "none"
    )

  p <- add_umap_arrow_axes(p, plot_df)

  save_plot_pdf(p, file.path(fig_dir, sprintf("%s_%s.pdf", out_name, timestamp_tag)), w_mm_umap, h_mm_umap, units = "mm")

  if (isTRUE(write_positive_cells)) {
    write.csv(plot_df %>% filter(red_positive), file.path(source_tab_dir, sprintf("%s_positive_cells_%s.csv", out_name, timestamp_tag)), row.names = FALSE)
  }
  invisible(p)
}

