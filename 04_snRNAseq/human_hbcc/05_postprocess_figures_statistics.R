compute_proportion_test_pair <- function(df, ct_name, feature_name) {
  stopifnot("positive" %in% colnames(df), "Patient" %in% colnames(df), "Group" %in% colnames(df))
  df <- df %>%
    mutate(Group = factor(normalize_group(Group), levels = display_levels),
           Patient = as.factor(Patient),
           .positive = as.integer(as.logical(positive))) %>%
    filter(Group %in% display_levels, !is.na(Patient), !is.na(.positive))

  per_donor <- df %>%
    group_by(Patient, Group) %>%
    summarise(n_total = dplyr::n(),
              n_positive = sum(.positive, na.rm = TRUE),
              proportion = ifelse(n_total > 0, n_positive / n_total, NA_real_),
              .groups = "drop") %>%
    mutate(Celltype_use = ct_name, feature_set = feature_name)

  if (nrow(df) < 2 || length(unique(df$Group)) < 2 || length(unique(df$Patient)) < 2 ||
      length(unique(df$.positive)) < 2) {
    glmm_p <- NA_real_; glmm_warning_flag <- TRUE
    glmm_warning_msg <- "insufficient groups, donors or binary outcome variation"
    glmm_error_msg <- ""
    eff_glmm <- list(estimate = NA_real_, se = NA_real_, ci_low = NA_real_, ci_high = NA_real_, p_value = NA_real_)
  } else {
    glmm_fit <- fit_glmmTMB_with_warnings(
      glmmTMB::glmmTMB(.positive ~ Group + (1 | Patient), data = df, family = binomial()))
    eff_glmm <- extract_glmmTMB_effect(glmm_fit$fit, "^Group")
    glmm_p <- eff_glmm$p_value
    glmm_warning_flag <- glmm_fit$warning_flag
    glmm_warning_msg <- glmm_fit$warning
    glmm_error_msg <- glmm_fit$error
  }
  n_zero_ctrl <- sum(per_donor$Group == display_levels[1] & per_donor$proportion == 0, na.rm = TRUE)
  n_zero_case <- sum(per_donor$Group == display_levels[2] & per_donor$proportion == 0, na.rm = TRUE)
  n_ctrl <- sum(per_donor$Group == display_levels[1], na.rm = TRUE)
  n_case <- sum(per_donor$Group == display_levels[2], na.rm = TRUE)
  fc_ha <- compute_fold_change_HA(per_donor, ctrl_level = display_levels[1], case_level = display_levels[2], pseudocount = 0.5)
  list(
    per_animal = per_donor,
    per_donor = per_donor,
    glmm_p = glmm_p,
    glmm_warning_flag = glmm_warning_flag,
    glmm_warning_msg = glmm_warning_msg,
    glmm_error_msg = glmm_error_msg,
    n_total_cells = nrow(df),
    n_donors_per_group = sprintf("%d/%d", n_ctrl, n_case),
    n_donors_zero_positive_ctrl = n_zero_ctrl,
    n_donors_zero_positive_case = n_zero_case,
    log_OR = eff_glmm$estimate, log_OR_se = eff_glmm$se,
    log_OR_ci_low = eff_glmm$ci_low, log_OR_ci_high = eff_glmm$ci_high,
    OR = exp(eff_glmm$estimate),
    OR_ci_low = exp(eff_glmm$ci_low), OR_ci_high = exp(eff_glmm$ci_high),
    ctrl_rate_HA = fc_ha$ctrl_rate_HA, case_rate_HA = fc_ha$case_rate_HA,
    fold_change_HA = fc_ha$fold_change, log2_fc_HA = fc_ha$log2_fc,
    pseudocount_method = fc_ha$pseudocount_method
  )
}

mixed_binary_interaction_test <- function(data, ct_pair = c("ExcitNeu", "InhibNeu")){
  df <- data %>%
    mutate(Group = factor(normalize_group(Group), levels = display_levels),
           Celltype_use = factor(Celltype_use, levels = ct_pair),
           Patient = as.factor(Patient),
           .y = as.integer(as.logical(positive))) %>%
    filter(Group %in% display_levels, Celltype_use %in% ct_pair, !is.na(.y), !is.na(Patient))

  if (nrow(df) < 2 || length(unique(df$Group)) < 2 ||
      length(unique(df$Celltype_use)) < 2 || length(unique(df$Patient)) < 2 ||
      length(unique(df$.y)) < 2) {
    return(data.frame(
      primary_method = "glmmTMB_binomial_group_by_celltype_random_patient",
      primary_p = NA_real_, interaction_log_OR = NA_real_,
      interaction_log_OR_ci_low = NA_real_, interaction_log_OR_ci_high = NA_real_,
      primary_warning = "insufficient groups, cell types, donors or outcome variation",
      primary_error = "", primary_warning_flag = TRUE,
      n_cells = nrow(df), n_patients = length(unique(df$Patient)),
      stringsAsFactors = FALSE))
  }
  fit_res <- fit_glmmTMB_with_warnings(
    glmmTMB::glmmTMB(.y ~ Group * Celltype_use + (1 | Patient), data = df, family = binomial()))
  eff <- extract_glmmTMB_effect(fit_res$fit, "Group.*:Celltype_use|Celltype_use.*:Group")
  data.frame(
    primary_method = "glmmTMB_binomial_group_by_celltype_random_patient",
    primary_p = eff$p_value,
    interaction_term = eff$term,
    interaction_log_OR = eff$estimate,
    interaction_log_OR_ci_low = eff$ci_low,
    interaction_log_OR_ci_high = eff$ci_high,
    interaction_OR = exp(eff$estimate),
    interaction_OR_ci_low = exp(eff$ci_low),
    interaction_OR_ci_high = exp(eff$ci_high),
    primary_warning = fit_res$warning, primary_error = fit_res$error,
    primary_warning_flag = fit_res$warning_flag,
    n_cells = nrow(df), n_patients = length(unique(df$Patient)),
    stringsAsFactors = FALSE)
}

